extern "C" void ex_hermes_set_host_call(
    ExactHermesRuntime* runtime,
    char* (*callback)(const char* op, const char* args_json)) {
  // @ref LLP 0002#the-__hostcall-bridge--the-generic-host-channel — the
  // string-typed catch-all bridge is diagnostic-only; an armed runtime must
  // expose only its dedicated, capability-aware native APIs.
  if (!runtime || runtime->armed) return;
  // Restricted worklet runtimes never get __hostCall (LLP 0297 §4.3).
  if (runtime->restricted) return;
  runtime->host_call_fn = callback;

  // Install (or reinstall) the __hostCall JS function
  auto& rt = *runtime->runtime;
  auto hostCallFn = facebook::jsi::Function::createFromHostFunction(
      rt,
      facebook::jsi::PropNameID::forAscii(rt, "__hostCall"),
      2,
      [runtime](facebook::jsi::Runtime& rt,
                const facebook::jsi::Value&,
                const facebook::jsi::Value* args,
                size_t count) -> facebook::jsi::Value {
        if (!runtime->host_call_fn || count < 1) {
          throw facebook::jsi::JSError(rt, "__hostCall: no callback registered or wrong arity");
        }
        auto op = hostCallOpToString(rt, args, count);
        auto argsJson = hostCallArgsToJson(rt, args, count);

        char* result = runtime->host_call_fn(op.c_str(), argsJson.c_str());
        if (!result) {
          return facebook::jsi::Value::null();
        }

        // Result is '+json' (success) / '-message' (error), decoded by the
        // shared sigil helper.
        std::string resultStr(result);
        free(result);

        facebook::jsi::Value value;
        std::string errorMessage;
        if (!decodeHostCallPayload(rt, resultStr, value, errorMessage)) {
          throw facebook::jsi::JSError(rt, errorMessage);
        }
        return value;
      });
  rt.global().setProperty(rt, "__hostCall", std::move(hostCallFn));
}

// LLP 0297 W3 (exact repo): the async host-call channel. `__hostCallAsync(op,
// argsJson)` returns a Promise; the registered native callback receives a
// call id and later completes it — from any thread — via
// ex_hermes_resolve_host_call, which delivers resolution on the runtime
// thread through pushRuntimeCallback (the same discipline as fetch).
extern "C" void ex_hermes_set_host_call_async(
    ExactHermesRuntime* runtime,
    void (*callback)(ExactHermesRuntime* runtime,
                     uint64_t call_id,
                     const char* op,
                     const char* args_json)) {
  // @ref LLP 0002#the-__hostcall-bridge--the-generic-host-channel — armed
  // runtimes fail closed before storing a generic callback or mutating the
  // global object, including replacement attempts made after lockdown.
  if (!runtime || runtime->armed) return;
  // Restricted worklet runtimes never get __hostCallAsync (LLP 0297 §4.3).
  if (runtime->restricted) return;
  runtime->host_call_async_fn = callback;

  auto& rt = *runtime->runtime;
  auto hostCallAsyncFn = facebook::jsi::Function::createFromHostFunction(
      rt,
      facebook::jsi::PropNameID::forAscii(rt, "__hostCallAsync"),
      2,
      [runtime](facebook::jsi::Runtime& rt,
                const facebook::jsi::Value&,
                const facebook::jsi::Value* args,
                size_t count) -> facebook::jsi::Value {
        if (!runtime->host_call_async_fn || count < 1) {
          throw facebook::jsi::JSError(
              rt, "__hostCallAsync: no callback registered or wrong arity");
        }
        auto op = std::make_shared<std::string>(hostCallOpToString(rt, args, count));
        auto argsJson =
            std::make_shared<std::string>(hostCallArgsToJson(rt, args, count));

        auto promiseCtor = rt.global().getPropertyAsFunction(rt, "Promise");
        auto executor = facebook::jsi::Function::createFromHostFunction(
            rt,
            facebook::jsi::PropNameID::forAscii(rt, "executor"),
            2,
            [runtime, op, argsJson](facebook::jsi::Runtime& rt,
                                    const facebook::jsi::Value&,
                                    const facebook::jsi::Value* args,
                                    size_t count) -> facebook::jsi::Value {
              if (count < 2 || !args[0].isObject() || !args[1].isObject()) {
                throw facebook::jsi::JSError(
                    rt, "__hostCallAsync: malformed executor invocation");
              }
              auto resolve = std::make_shared<facebook::jsi::Function>(
                  args[0].asObject(rt).asFunction(rt));
              auto reject = std::make_shared<facebook::jsi::Function>(
                  args[1].asObject(rt).asFunction(rt));

              auto target = exactRuntimeCallbackTarget(runtime);
              uint64_t callId = registerHostCallTarget(target);
              if (callId == 0) {
                throw facebook::jsi::JSError(
                    rt, "__hostCallAsync: call id space exhausted");
              }
              {
                std::lock_guard<std::mutex> lock(runtime->hostCallAsyncMutex);
                runtime->hostCallAsyncCallbacks[callId] = {std::move(resolve),
                                                           std::move(reject)};
              }
              runtime->host_call_async_fn(runtime, callId, op->c_str(), argsJson->c_str());
              return facebook::jsi::Value::undefined();
            });
        return promiseCtor.callAsConstructor(rt, executor);
      });
  rt.global().setProperty(rt, "__hostCallAsync", std::move(hostCallAsyncFn));
}

extern "C" void ex_hermes_resolve_host_call(ExactHermesRuntime* runtime,
                                            uint64_t call_id,
                                            const char* payload) {
  if (!runtime) return;

  auto target = takeHostCallTarget(runtime, call_id);
  if (!target || !exactPinRuntimeNativeWorker(target)) return;

  std::shared_ptr<facebook::jsi::Function> resolve;
  std::shared_ptr<facebook::jsi::Function> reject;
  bool extracted = withRuntimePinned(target, [&]() {
    // ENG-22925: pin the runtime across the liveness check AND the callback
    // extraction. ex_hermes_destroy holds g_runtimeRegistryMutex across the
    // delete, so this closes the TOCTOU gap that let a concurrent free land
    // between the old lock-then-release runtimeIsAlive and the
    // hostCallAsyncMutex deref (routinely reachable post-W4b: MainActor
    // host-call resolutions vs. runtime-thread engine destroy on dev-server
    // reconnect). Lock order registry -> hostCallAsync; destroy never locks
    // hostCallAsync, so there is no inversion, and the notify inside the
    // pushRuntimeCallback below fires outside this mutex.
    // @ref LLP 0002#the-__hostcall-bridge--the-generic-host-channel — an armed
    // runtime must reject generic async completions before extracting pending
    // callbacks. Check `armed` under the registry pin so a stale pointer is
    // never dereferenced before the liveness check.
    if (runtime->armed) return;
    std::lock_guard<std::mutex> lock(runtime->hostCallAsyncMutex);
    auto it = runtime->hostCallAsyncCallbacks.find(call_id);
    if (it == runtime->hostCallAsyncCallbacks.end()) return;
    resolve = std::move(it->second.resolve);
    reject = std::move(it->second.reject);
    runtime->hostCallAsyncCallbacks.erase(it);
  });
  if (!extracted || !resolve || !reject) {
    exactUnpinRuntimeNativeWorker(target);
    return;
  }
  std::string payloadCopy = payload ? payload : "";
  pushRuntimeCallback(
      target,
      [resolve, reject, payloadCopy](facebook::jsi::Runtime& rt) {
        try {
          facebook::jsi::Value value;
          std::string errorMessage;
          if (decodeHostCallPayload(rt, payloadCopy, value, errorMessage)) {
            resolve->call(rt, value);
          } else {
            reject->call(rt, facebook::jsi::JSError(rt, errorMessage).value());
          }
        } catch (const std::exception& e) {
          try {
            reject->call(rt, facebook::jsi::JSError(rt, e.what()).value());
          } catch (...) {
          }
        } catch (...) {
        }
      });
  exactUnpinRuntimeNativeWorker(target);
}

