function createEncodingError(message: string): TypeError & { code: string } {
  const error = new TypeError(message) as TypeError & { code: string };
  error.code = "ERR_ENCODING_INVALID_ENCODED_DATA";
  return error;
}

function isValidUTF8Continuation(
  startByte: number,
  continuationByte: number,
  position: number
): boolean {
  if ((continuationByte & 0xc0) !== 0x80) {
    return false;
  }

  if (position !== 1) {
    return true;
  }

  if ((startByte & 0xf0) === 0xe0) {
    if (startByte === 0xe0 && continuationByte < 0xa0) {
      return false;
    }
    if (startByte === 0xed && continuationByte > 0x9f) {
      return false;
    }
  }

  if ((startByte & 0xf8) === 0xf0) {
    if (startByte === 0xf0 && continuationByte < 0x90) {
      return false;
    }
    if (startByte === 0xf4 && continuationByte > 0x8f) {
      return false;
    }
  }

  return true;
}

