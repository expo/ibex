export function parseWebGpuProductionPlanSource(
  source,
  label = WEBGPU_PRODUCTION_PLAN_PATH,
) {
  if (!source.startsWith(PLAN_PREFIX) || !source.endsWith(PLAN_SUFFIX)) {
    throw new Error(`${label}: generated production-plan envelope drifted`);
  }
  let plan;
  try {
    plan = JSON.parse(
      source.slice(PLAN_PREFIX.length, source.length - PLAN_SUFFIX.length),
    );
  } catch (error) {
    throw new Error(`${label}: invalid generated plan JSON: ${error.message}`);
  }
  if (
    plan?.schema !== "ibex/webgpu-production-wrapper-plan/1" ||
    !Array.isArray(plan.routes) ||
    plan.routes.length === 0
  ) {
    throw new Error(`${label}: invalid production-plan shape`);
  }
  return plan;
}

export function authenticateWebGpuProductionPlan({
  plan,
  authority,
  planRawContentSha256 = null,
  authorityRawContentSha256 = null,
}) {
  const authenticated = validateWebGpuWrapperAuthority(authority);
  const expectedRoutes = authenticated.payload.operations.map(routeProjection);
  if (canonical(plan.routes) !== canonical(expectedRoutes)) {
    throw new Error(
      "WebGPU production-plan routes differ from authenticated wrapper authority",
    );
  }
  if (
    plan.profileId !== authenticated.payload.profileId ||
    plan.scopeId !== authenticated.payload.scopeId ||
    canonical(plan.digests) !== canonical(authenticated.computed)
  ) {
    throw new Error(
      "WebGPU production-plan profile, scope, or digest identity is unauthenticated",
    );
  }
  const operationIds = expectedRoutes.map((route) => route.operationId);
  if (
    plan.activeRouteSubset?.scopeId !== plan.scopeId ||
    plan.activeRouteSubset?.operationCount !== expectedRoutes.length ||
    canonical(plan.activeRouteSubset?.operationIds) !== canonical(operationIds) ||
    plan.activeRouteSubset?.capsecDisposition !==
      "construction-private-source-derived-cells-public-closed"
  ) {
    throw new Error(
      "WebGPU production-plan active-route subset differs from authenticated routes",
    );
  }
  const stagedIds = new Set(
    (plan.stagedWorkloadClosure?.additionalOperations ?? []).map(
      (operation) => operation.operationId,
    ),
  );
  const stagedOverlap = operationIds.filter((operationId) =>
    stagedIds.has(operationId),
  );
  if (stagedOverlap.length > 0) {
    throw new Error(
      `WebGPU staged routes leaked into the active production plan: ${stagedOverlap.join(", ")}`,
    );
  }
  if (
    plan.productSemanticExtension?.publicInstallDisposition !== "absent" ||
    plan.productSemanticExtension?.embeddedCodecDisposition !== "absent" ||
    plan.productSemanticExtension?.supportClaim !== "none" ||
    plan.productSemanticExtension?.capsecDisposition !==
      "construction-private-source-derived-cells-public-closed"
  ) {
    throw new Error(
      "WebGPU production-plan product extension crossed the private support boundary",
    );
  }
  for (const [index, route] of expectedRoutes.entries()) {
    if (
      !Number.isInteger(route.wireId) ||
      route.wireId <= 0 ||
      Object.keys(route).some((key) => !ROUTE_KEYS.includes(key))
    ) {
      throw new Error(`WebGPU route ${index} has an invalid authenticated identity`);
    }
  }
  return {
    plan,
    routes: expectedRoutes,
    authenticatedDigests: authenticated.computed,
    providerIdentity: {
      abiVersion: authenticated.payload.providerDescriptor.serviceAbiVersion,
      topologyId: authenticated.payload.providerDescriptor.topologyId,
      profileId: authenticated.payload.providerDescriptor.profileId,
      profileDigest: authenticated.payload.providerDescriptor.profileDigest,
      webgpuCVocabularyDigest:
        authenticated.payload.providerDescriptor.webgpuCVocabularyDigest,
      operationSetDigest:
        authenticated.payload.providerDescriptor.operationSetDigest,
      semanticProgramDigest:
        authenticated.payload.providerDescriptor.semanticProgramDigest,
      runtimeRoutingDigest:
        authenticated.payload.providerDescriptor.runtimeRoutingDigest,
      sortedOperationIds:
        authenticated.payload.providerDescriptor.sortedOperationIds,
    },
    planRawContentSha256,
    authorityRawContentSha256,
  };
}

export function loadAuthenticatedWebGpuProductionPlan(repoRoot) {
  const planPath = path.join(repoRoot, WEBGPU_PRODUCTION_PLAN_PATH);
  const authorityPath = path.join(repoRoot, WEBGPU_WRAPPER_AUTHORITY_PATH);
  const planBytes = fs.readFileSync(planPath);
  const authorityBytes = fs.readFileSync(authorityPath);
  const plan = parseWebGpuProductionPlanSource(
    new TextDecoder("utf-8", { fatal: true }).decode(planBytes),
  );
  let authority;
  try {
    authority = JSON.parse(
      new TextDecoder("utf-8", { fatal: true }).decode(authorityBytes),
    );
  } catch (error) {
    throw new Error(
      `${WEBGPU_WRAPPER_AUTHORITY_PATH}: invalid authority JSON: ${error.message}`,
    );
  }
  return authenticateWebGpuProductionPlan({
    plan,
    authority,
    planRawContentSha256: sha256Hex(planBytes),
    authorityRawContentSha256: sha256Hex(authorityBytes),
  });
}

export function webGpuOperationSemantics(route) {
  if (
    route.logicalExecutionKind === "cleanup-service" ||
    route.providerSubmission === "semantic-call-authority-reducing"
  ) {
    return {
      classification: "non-capability",
      rationaleId: "authority-release",
      privateCellDisposition: "non-capability",
      providerBridge: "submit",
      positiveAuthority: "not-applicable-authority-reducing",
      authoritySession: {
        decisionKind: "structural-authority-reducing",
        stages: ["requested", "commit", "repeat"],
        targetCellDisposition: "non-capability",
      },
    };
  }
  if (route.providerSubmission === "semantic-service-timeline") {
    return {
      classification: "non-capability",
      rationaleId: "authority-control-plane",
      privateCellDisposition: "non-capability",
      providerBridge: null,
      positiveAuthority: "not-applicable-control-plane",
      authoritySession: {
        decisionKind: "structural-control-plane",
        stages: ["requested", "commit", "repeat"],
        targetCellDisposition: "non-capability",
      },
    };
  }
  if (
    route.dispatchClass === "wrapper-local" ||
    route.dispatchClass === "wrapper-property-read"
  ) {
    return {
      classification: "non-capability",
      rationaleId:
        route.operationId === "GPU.getPreferredCanvasFormat"
          ? "pure-in-memory-compute"
          : "retained-object-wrapper",
      privateCellDisposition: "non-capability",
      providerBridge: null,
      positiveAuthority: "not-applicable-wrapper-local",
      authoritySession: null,
    };
  }
  if (route.dispatchClass === "wrapper-recording") {
    return {
      classification: "non-capability",
      rationaleId: "retained-object-wrapper",
      privateCellDisposition: "non-capability",
      providerBridge: null,
      positiveAuthority: "not-applicable-wrapper-recording",
      authoritySession: null,
    };
  }
  if (route.dispatchClass === "wrapper-local-deferred-service") {
    return {
      classification: "closed",
      cap: "ipc:channel",
      privateCellDisposition: "closed",
      providerBridge: null,
      positiveAuthority: "absent-closed-deferred-service-edge",
      authoritySession: null,
    };
  }
  if (
    route.providerSubmission === "semantic-call-promise-completion" ||
    route.providerSubmission === "semantic-call-device-timeline"
  ) {
    return {
      classification: "closed",
      cap: "ipc:channel",
      // The public edge remains closed. This separate construction-private
      // cell is complete only for the native authority-session callback; it
      // does not advertise a target, mint a grant, or install navigator.gpu.
      privateCellDisposition: "complete",
      providerBridge: "submit",
      positiveAuthority: "typed-gpu-operation-no-public-grant-issuer",
      authoritySession: {
        decisionKind: "typed-positive",
        action: "gpu:operation",
        stages: ["requested", "commit", "repeat"],
        targetCellDisposition: "complete",
      },
    };
  }
  throw new Error(
    `${route.operationId}: unreviewed WebGPU CapSec route semantics ${route.dispatchClass}/${route.logicalExecutionKind}/${route.providerSubmission}`,
  );
}

function webGpuRouteEvidence(route) {
  const routeIdentityHash = fnv1a32(
    `${route.operationId}\0${route.wireId}`,
  );
  return {
    sourceRefs: [
      `${WEBGPU_PRODUCTION_PLAN_PATH}#route:${route.operationId}:${route.wireId}`,
      `${WEBGPU_WRAPPER_AUTHORITY_PATH}#payload.operations:${route.operationId}:${route.wireId}`,
    ].sort(compareText),
    surfaceBranchId: `authenticated-production-route-${routeIdentityHash}`,
    implementationBranchSuffix:
      `authenticated.production.route.${routeIdentityHash}`,
  };
}

function webGpuPresentationAuthorityEvidence(branch) {
  const branchIdentityHash = fnv1a32(branch.operationId);
  return {
    sourceRefs: [
      `packages/ibex-runtime-js/src/webgpu/production-wrapper.ts#presentation-authority:${branch.id}`,
      `src/host/gpu_authority.rs#presentation-authority:${branch.id}`,
    ].sort(compareText),
    surfaceBranchId:
      `authenticated-presentation-authority-${branch.id}-${branchIdentityHash}`,
    implementationBranchSuffix:
      `authenticated.presentation.authority.${branch.id}.${branchIdentityHash}`,
  };
}

export function webGpuPresentationAuthoritySemantics(operationId) {
  const branch = WEBGPU_PRESENTATION_AUTHORITY_BRANCHES.find(
    (candidate) => candidate.operationId === operationId,
  );
  if (!branch) return null;
  return {
    ...branch,
    classification: "closed",
    cap: "ipc:channel",
    privateCellDisposition: "complete",
    providerBridge: "submit",
    positiveAuthority:
      "typed-gpu-presentation-operation-no-public-grant-issuer",
    authoritySession: {
      decisionKind: "typed-positive",
      action: "gpu:operation",
      stages: ["requested", "commit", "repeat"],
      targetCellDisposition: "complete",
    },
  };
}

export function buildWebGpuOperationSurfaces(authenticated) {
  const routeSurfaces = authenticated.routes.map((route) => {
    const semantics = webGpuOperationSemantics(route);
    const name = `construction-private:webgpu:${route.operationId}`;
    const evidence = webGpuRouteEvidence(route);
    const branch = {
      branchKind: "single",
      id: evidence.surfaceBranchId,
      kind: "single",
      route: "authenticated-webgpu-production-route",
      sourceRefs: evidence.sourceRefs,
      targetVariant: "all",
    };
    return {
      kind: "native-op",
      name,
      observedKey: `native-op:${name}`,
      sourceRefs: evidence.sourceRefs,
      metadata: {
        evidenceType: "authenticated-webgpu-production-route",
        surfaceType: "webgpu-production-operation",
        operationId: route.operationId,
        wireId: route.wireId,
        routeIdentity: route,
        authenticatedDigests: authenticated.authenticatedDigests,
        publicInstallDisposition: "absent",
        embeddedExecutableCodecDisposition: "absent",
        platformSupportClaim: "none",
        positiveAuthority: semantics.positiveAuthority,
        providerBridge: semantics.providerBridge,
        branches: [branch],
        installationBranches: [branch],
        semanticRoles: ["construction-private-webgpu-operation"],
      },
    };
  });
  const presentationSurfaces = WEBGPU_PRESENTATION_AUTHORITY_BRANCHES.map(
    (branch) => {
      const semantics = webGpuPresentationAuthoritySemantics(
        branch.operationId,
      );
      const name =
        `construction-private:webgpu-presentation:${branch.operationId}`;
      const evidence = webGpuPresentationAuthorityEvidence(branch);
      const installationBranch = {
        branchKind: "single",
        id: evidence.surfaceBranchId,
        kind: "single",
        route: "authenticated-webgpu-presentation-authority",
        sourceRefs: evidence.sourceRefs,
        targetVariant: "all",
      };
      return {
        kind: "native-op",
        name,
        observedKey: `native-op:${name}`,
        sourceRefs: evidence.sourceRefs,
        metadata: {
          evidenceType: "authenticated-webgpu-presentation-authority",
          surfaceType: "webgpu-presentation-authority-operation",
          presentationBranchId: branch.id,
          operationId: branch.operationId,
          authenticatedDigests: authenticated.authenticatedDigests,
          publicInstallDisposition: "absent",
          platformSupportClaim: "none",
          positiveAuthority: semantics.positiveAuthority,
          providerBridge: semantics.providerBridge,
          branches: [installationBranch],
          installationBranches: [installationBranch],
          semanticRoles: [
            "construction-private-webgpu-presentation-authority",
          ],
        },
      };
    },
  );
  return [...routeSurfaces, ...presentationSurfaces];
}

function edgeBySurfaceName(coverage, surfaceName) {
  const rows = coverage.edges.filter(
    (edge) =>
      edge.surface.kind === "native-op" && edge.surface.name === surfaceName,
  );
  if (rows.length !== 1) {
    throw new Error(
      `${surfaceName}: expected one generated CapSec edge, found ${rows.length}`,
    );
  }
  return rows[0];
}

function expectedImplementationRow(route, edge) {
  const evidence = webGpuRouteEvidence(route);
  const observedKey =
    `native-op:construction-private:webgpu:${route.operationId}`;
  const branchId = `${edge.id}.${evidence.implementationBranchSuffix}`;
  return {
    edgeId: edge.id,
    observedKey,
    branchId,
    enforcementBranchId: branchId,
    enforcementRoute: {
      kind: "surface-branch",
      proofPaths: [observedKey],
      proofSourceRefs: evidence.sourceRefs,
      sourceRefs: evidence.sourceRefs,
      terminalObservedKey: observedKey,
    },
    branchKind: "single",
    targetVariant: "all",
    targetApplicability: {
      kind: "all",
    },
    sourceRefs: evidence.sourceRefs,
    implementationOwner: "WP4",
    fixtureObligations: fixtureObligationsForBranch(edge, branchId),
  };
}

