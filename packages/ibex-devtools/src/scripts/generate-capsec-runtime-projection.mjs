/**
 * Generate the CapSec projection that identifies authorization semantics built
 * into a compiled runtime stub. Source/CLI coverage registries are
 * intentionally absent: they are review evidence, not runtime behavior.
 *
 * @ref LLP 0029#2-executable-layout-stub-envelope-footer — stub compatibility pins runtime enforcement without inheriting CLI-only registry churn
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  canonicalJson,
  computeDomainDigest,
  parseJsonStrict,
} from "./capsec-contract.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../../..");
const schema = "ibex/capsec-runtime-projection/1";
const domain = "ibex:capsec-runtime-projection:1";

const definitionsPath = path.join(
  repoRoot,
  "capsec/registry/capability-definitions.json",
);
const rulesPath = path.join(repoRoot, "capsec/registry/policy-rules.json");
const canonicalOutPath = path.join(
  repoRoot,
  "vendored-generated/capsec-runtime-projection.canonical.json",
);
const rustOutPath = path.join(
  repoRoot,
  "src/capsec_runtime_projection_generated.rs",
);
const tsOutPath = path.join(
  repoRoot,
  "packages/ibex-runtime-js/src/security/capsec-runtime-projection.generated.ts",
);

const definitionRuntimeFields = Object.freeze([
  "channels",
  "globality",
  "id",
  "lifecycle",
  "normalizationProfile",
  "occurrenceSchema",
  "resourceKinds",
  "selectorConstraints",
  "selectorSchema",
  "staticOnly",
]);

const ruleRuntimeFields = Object.freeze([
  "cacheKeyFields",
  "classifierRules",
  "decisionPrecedence",
  "decisionStrata",
  "digestContract",
  "dynamicAuthority",
  "effectSemantics",
  "execution",
  "handles",
  "initialProfile",
  "normalizationProfiles",
  "principalSemantics",
  "resourceRules",
]);

function requireObject(value, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object`);
  }
  return value;
}

function projectFields(value, names, label) {
  const object = requireObject(value, label);
  const projected = {};
  for (const name of names) {
    if (!Object.hasOwn(object, name)) {
      if (name === "selectorConstraints") continue;
      throw new Error(`${label} omits required runtime field ${name}`);
    }
    projected[name] = object[name];
  }
  return projected;
}

export function buildRuntimeProjection(definitions, rules) {
  requireObject(definitions, "capability definitions");
  requireObject(rules, "policy rules");
  if (
    definitions.definitionsSchema !== "ibex/capsec-definitions/1" ||
    rules.rulesSchema !== "ibex/capsec-rules/1"
  ) {
    throw new Error("CapSec runtime projection source schemas are unsupported");
  }
  if (
    definitions.profile !== rules.profile ||
    definitions.semanticCore !== rules.semanticCore
  ) {
    throw new Error("CapSec runtime projection authorities disagree on profile identity");
  }
  if (!Array.isArray(definitions.definitions) || definitions.definitions.length === 0) {
    throw new Error("CapSec runtime projection has no capability definitions");
  }
  const projectedDefinitions = definitions.definitions
    .map((definition, index) =>
      projectFields(definition, definitionRuntimeFields, `capability definition ${index}`),
    )
    .sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0));
  if (
    projectedDefinitions.some(
      (definition, index) =>
        index > 0 && definition.id === projectedDefinitions[index - 1].id,
    )
  ) {
    throw new Error("CapSec runtime projection contains duplicate capability ids");
  }
  const projectedRules = projectFields(rules, ruleRuntimeFields, "policy rules");
  // The command spelling is review guidance, not executable enforcement.
  const execution = { ...projectedRules.execution };
  delete execution.auditWorkflow;
  delete execution.contractFixtureWorkflow;
  projectedRules.execution = execution;

  return {
    schema,
    profile: rules.profile,
    semanticCore: rules.semanticCore,
    acceptedSchemas: {
      armedSnapshot: "ibex/capsec-armed/1",
      canonicalPolicy: "ibex/capsec-policy/2",
      capabilityDefinitions: definitions.definitionsSchema,
      policyRules: rules.rulesSchema,
    },
    definitions: projectedDefinitions,
    rules: projectedRules,
  };
}

function renderRust(digest) {
  return `// @generated by bun run generate:capsec-runtime-projection; do not edit.\n` +
    `// @ref LLP 0029#2-executable-layout-stub-envelope-footer — generated constants pin only runtime-relevant CapSec semantics\n` +
    `pub const CAPSEC_RUNTIME_PROJECTION_SCHEMA: &str = ${JSON.stringify(schema)};\n` +
    `pub const CAPSEC_RUNTIME_PROJECTION_DOMAIN: &str = ${JSON.stringify(domain)};\n` +
    `pub const CAPSEC_RUNTIME_PROJECTION_DIGEST: &str =\n` +
    `    ${JSON.stringify(digest)};\n` +
    `\n#[cfg(test)]\nmod tests {\n` +
    `    #[test]\n` +
    `    fn generated_capsec_runtime_projection_digest_matches_bytes() {\n` +
    `        let bytes = include_bytes!(concat!(\n` +
    `            env!("CARGO_MANIFEST_DIR"),\n` +
    `            "/vendored-generated/capsec-runtime-projection.canonical.json"\n` +
    `        ));\n` +
    `        let text = std::str::from_utf8(bytes).unwrap();\n` +
    `        let value = capsec_semantics::strict_json::parse_strict(text).unwrap();\n` +
    `        assert_eq!(\n` +
    `            capsec_semantics::canonical::to_jcs_bytes(&value).unwrap(),\n` +
    `            bytes\n` +
    `        );\n` +
    `        assert_eq!(value["schema"], super::CAPSEC_RUNTIME_PROJECTION_SCHEMA);\n` +
    `        assert_eq!(\n` +
    `            capsec_semantics::digest::compute_domain_digest(\n` +
    `                super::CAPSEC_RUNTIME_PROJECTION_DOMAIN,\n` +
    `                &value,\n` +
    `                &[],\n` +
    `            )\n` +
    `            .unwrap(),\n` +
    `            super::CAPSEC_RUNTIME_PROJECTION_DIGEST,\n` +
    `        );\n` +
    `    }\n` +
    `}\n`;
}

function renderTypeScript(digest) {
  return `// GENERATED FILE - DO NOT EDIT.\n` +
    `// Source authorities: capsec/registry/capability-definitions.json and policy-rules.json\n` +
    `// Generator: bun packages/ibex-devtools/src/scripts/generate-capsec-runtime-projection.mjs\n\n` +
    `export const CAPSEC_RUNTIME_PROJECTION_SCHEMA = ${JSON.stringify(schema)};\n` +
    `export const CAPSEC_RUNTIME_PROJECTION_DOMAIN = ${JSON.stringify(domain)};\n` +
    `export const CAPSEC_RUNTIME_PROJECTION_DIGEST = ${JSON.stringify(digest)};\n`;
}

export function renderRuntimeProjection(definitions, rules) {
  const projection = buildRuntimeProjection(definitions, rules);
  const canonical = canonicalJson(projection);
  const digest = computeDomainDigest(domain, projection);
  return {
    projection,
    digest,
    outputs: [
      [canonicalOutPath, canonical],
      [rustOutPath, renderRust(digest)],
      [tsOutPath, renderTypeScript(digest)],
    ],
  };
}

function readStrict(filePath) {
  return parseJsonStrict(fs.readFileSync(filePath), path.relative(repoRoot, filePath));
}

export function run({ check }) {
  const rendered = renderRuntimeProjection(readStrict(definitionsPath), readStrict(rulesPath));
  const stale = [];
  for (const [outPath, content] of rendered.outputs) {
    if (fs.existsSync(outPath) && fs.readFileSync(outPath, "utf8") === content) continue;
    if (check) stale.push(path.relative(repoRoot, outPath));
    else {
      fs.mkdirSync(path.dirname(outPath), { recursive: true });
      fs.writeFileSync(outPath, content);
      console.log(`wrote ${path.relative(repoRoot, outPath)}`);
    }
  }
  if (stale.length > 0) {
    throw new Error(
      `CapSec runtime projection is stale: ${stale.join(", ")}; run bun run generate:capsec-runtime-projection`,
    );
  }
  if (check) console.log("CapSec runtime projection is fresh");
  return rendered;
}

if (path.resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  try {
    run({ check: process.argv.includes("--check") });
  } catch (error) {
    console.error(`error: ${error.message}`);
    process.exit(1);
  }
}
