  bool _tracing = startup_trace_enabled();
  bool sharedRuntimeInstalled = false;
  auto _t_host_functions = std::chrono::steady_clock::now();
  #define IG_TRACE_START(n) _t_##n = std::chrono::steady_clock::now()
  #define IG_TRACE_END(n) if (_tracing) { \
    auto _el = std::chrono::duration_cast<std::chrono::microseconds>( \
        std::chrono::steady_clock::now() - _t_##n).count(); \
    fprintf(stderr, "[startup]   %-28s %6lld us (%5.1f ms)\n", \
            #n, (long long)_el, _el / 1000.0); }

  auto& rt = *handle->runtime;
  auto _t_console_globals = std::chrono::steady_clock::now();
  installConsoleGlobals(handle);
  ensureExactEmbedderObject(handle);
  IG_TRACE_END(console_globals);

  bool skip_host_functions = env_flag_enabled("EX_SKIP_STARTUP_HOST_FUNCTIONS");
