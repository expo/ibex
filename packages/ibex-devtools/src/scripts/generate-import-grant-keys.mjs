/**
 * Generate the runtime refusal vocabulary from the build parser's authoritative
 * grant-key constant.  `needs` is retained as the historical loader spelling.
 *
 * @ref LLP 0022#6-imports-and-authority — prompt/runtime source may
 * not author build-time authority, and the refusal vocabulary must not drift
 * between the JavaScript grant parser and the Rust session parser.
 */

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GRANT_ATTRIBUTE_KEYS } from "./import-grants.mjs";
import {
  assertConfinedGeneratedFile,
  writeGeneratedFilesTransactionally,
} from "./generated-output-io.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export const repoRoot = path.resolve(__dirname, "..", "..", "..", "..");
export const grantParserPath = path.join(__dirname, "import-grants.mjs");
export const generatorPath = __filename;
export const generatedImportGrantKeyPaths = Object.freeze({
  rust: path.join(
    repoRoot,
    "vendored-generated",
    "import_grant_keys.generated.rs",
  ),
  javascript: path.join(
    repoRoot,
    "src",
    "engine",
    "bootstrap",
    "import-grant-keys.generated.js",
  ),
});
const generatedLlpRef = `// ${"@ref"} LLP 0022#6-imports-and-authority`;

function sha256(source) {
  return crypto.createHash("sha256").update(source).digest("hex");
}

function relative(filePath) {
  return path.relative(repoRoot, filePath).split(path.sep).join("/");
}

function rustString(value) {
  return JSON.stringify(value);
}

export function importGrantKeys(keys = GRANT_ATTRIBUTE_KEYS) {
  if (!Array.isArray(keys) || keys.length === 0) {
    throw new TypeError("GRANT_ATTRIBUTE_KEYS must be a non-empty array");
  }
  const closed = [...keys, "needs"];
  if (
    closed.some(
      (key) =>
        typeof key !== "string" || !/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(key),
    )
  ) {
    throw new TypeError("reserved import-grant keys must be identifier names");
  }
  if (new Set(closed).size !== closed.length) {
    throw new TypeError("reserved import-grant keys must be unique");
  }
  return Object.freeze(closed);
}

export function renderImportGrantKeyArtifacts({
  keys = importGrantKeys(),
  parserSource = fs.readFileSync(grantParserPath, "utf8"),
  generatorSource = fs.readFileSync(generatorPath, "utf8"),
} = {}) {
  const parserDigest = sha256(parserSource);
  const generatorDigest = sha256(generatorSource);
  const rustValues = keys.map((key) => `    ${rustString(key)},`).join("\n");
  const rust = [
    "// @generated by packages/ibex-devtools/src/scripts/generate-import-grant-keys.mjs",
    "// Source: packages/ibex-devtools/src/scripts/import-grants.mjs",
    `// Source SHA-256: ${parserDigest}`,
    `// Generator SHA-256: ${generatorDigest}`,
    "// Do not edit by hand.",
    generatedLlpRef,
    "",
    `pub const RESERVED_IMPORT_GRANT_KEYS: &[&str; ${keys.length}] = &[`,
    rustValues,
    "];",
    "",
  ].join("\n");
  const javascript = [
    "// @generated by packages/ibex-devtools/src/scripts/generate-import-grant-keys.mjs",
    "// Source: packages/ibex-devtools/src/scripts/import-grants.mjs",
    `// Source SHA-256: ${parserDigest}`,
    `// Generator SHA-256: ${generatorDigest}`,
    "// Do not edit by hand.",
    generatedLlpRef,
    "(function installGeneratedImportGrantKeys(globalObject) {",
    "  Object.defineProperty(globalObject, \"__exactGeneratedImportGrantKeys\", {",
    `    value: Object.freeze(${JSON.stringify(keys)}),`,
    "    writable: false,",
    "    enumerable: false,",
    "    configurable: true,",
    "  });",
    "})(globalThis);",
    "",
  ].join("\n");
  return { keys, parserDigest, generatorDigest, rust, javascript };
}

export function checkImportGrantKeyArtifacts(rendered) {
  const stale = [];
  for (const [kind, filePath] of Object.entries(generatedImportGrantKeyPaths)) {
    try {
      assertConfinedGeneratedFile(repoRoot, filePath, `${kind} import-grant keys`);
      const expected = kind === "rust" ? rendered.rust : rendered.javascript;
      if (fs.readFileSync(filePath, "utf8") !== expected) stale.push(relative(filePath));
    } catch {
      stale.push(relative(filePath));
    }
  }
  return stale;
}

export function writeImportGrantKeyArtifacts(rendered) {
  writeGeneratedFilesTransactionally(
    repoRoot,
    [
      {
        path: generatedImportGrantKeyPaths.rust,
        content: rendered.rust,
        label: "Rust import-grant keys",
      },
      {
        path: generatedImportGrantKeyPaths.javascript,
        content: rendered.javascript,
        label: "JavaScript import-grant keys",
      },
    ],
    () => {
      const stale = checkImportGrantKeyArtifacts(rendered);
      if (stale.length > 0) {
        throw new Error(`generated import-grant keys failed validation: ${stale.join(", ")}`);
      }
    },
  );
}

function main(argv) {
  const write = argv.includes("--write");
  const check = argv.includes("--check");
  const unknown = argv.filter((argument) => !["--write", "--check"].includes(argument));
  if (unknown.length > 0 || write === check) {
    throw new Error(
      "usage: bun packages/ibex-devtools/src/scripts/generate-import-grant-keys.mjs (--write|--check)",
    );
  }
  const rendered = renderImportGrantKeyArtifacts();
  if (write) {
    writeImportGrantKeyArtifacts(rendered);
    console.log(
      `wrote ${Object.values(generatedImportGrantKeyPaths).map(relative).join(", ")}`,
    );
    return;
  }
  const stale = checkImportGrantKeyArtifacts(rendered);
  if (stale.length > 0) {
    console.error(`import-grant key artifacts are stale: ${stale.join(", ")}`);
    process.exitCode = 1;
  } else {
    console.log(`import-grant keys checked: ${rendered.keys.join(", ")}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.stack : String(error));
    process.exitCode = 1;
  }
}
