function staleFullProjectionError(route) {
  return new Error(
    `${route.operationId}: full CapSec projections are stale for authenticated wire ID ${route.wireId}; run bun run generate:capsec-registry before generate:webgpu-capsec-registry`,
  );
}

export function buildWebGpuPrivateOperationRegistry({
  authenticated,
  coverage,
  implementationRows,
  targetCells,
  targetAdvertisements,
}) {
  if (targetAdvertisements.advertisements.length !== 0) {
    throw new Error(
      "construction-private WebGPU registry cannot promote a WP1 target advertisement",
    );
  }
  const bridgeEdges = Object.fromEntries(
    Object.entries(BRIDGE_SURFACE_NAMES).map(([name, surfaceName]) => [
      name,
      edgeBySurfaceName(coverage, surfaceName).id,
    ]),
  );
  const operations = [];
  const privateTargetCells = [];
  for (const route of authenticated.routes) {
    const semantics = webGpuOperationSemantics(route);
    const surfaceName = `construction-private:webgpu:${route.operationId}`;
    const edge = edgeBySurfaceName(coverage, surfaceName);
    if (edge.classification !== semantics.classification) {
      throw new Error(
        `${route.operationId}: generated edge classification drifted from route semantics`,
      );
    }
    const expectedImplementation = expectedImplementationRow(
      route,
      edge,
    );
    const implementationMatches = implementationRows.filter(
      (row) => row.edgeId === edge.id,
    );
    if (
      implementationMatches.length !== 1 ||
      canonical(implementationMatches[0]) !==
        canonical(expectedImplementation)
    ) {
      throw staleFullProjectionError(route);
    }
    const branches = [expectedImplementation.branchId];
    const wp1Cells = targetCells.cells.filter((cell) => cell.edgeId === edge.id);
    if (
      wp1Cells.length === 0 ||
      wp1Cells.some(
        (cell) => cell.disposition !== "unsupported" || cell.fixtures.length !== 0,
      )
    ) {
      throw new Error(
        `${route.operationId}: construction-private route promoted a WP1 target cell`,
      );
    }
    if (
      wp1Cells.some(
        (cell) =>
          canonical(cell.implementationBranchIds) !== canonical(branches),
      )
    ) {
      throw staleFullProjectionError(route);
    }
    operations.push({
      operationId: route.operationId,
      wireId: route.wireId,
      edgeId: edge.id,
      edgeClassification: edge.classification,
      dispatchClass: route.dispatchClass,
      logicalExecutionKind: route.logicalExecutionKind,
      providerSubmission: route.providerSubmission,
      receiverHandleKind: route.receiverHandleKind,
      wrapperAllocatedTargetHandleKind:
        route.wrapperAllocatedTargetHandleKind,
      operationInstanceIdentity: route.operationInstanceIdentity,
      promiseIdentity: route.promiseIdentity,
      privateTargetCellId: `${edge.id}.${WEBGPU_PRIVATE_TARGET_ID}`,
      authoritySession: semantics.authoritySession,
    });
    privateTargetCells.push({
      id: `${edge.id}.${WEBGPU_PRIVATE_TARGET_ID}`,
      edgeId: edge.id,
      target: {
        kind: "construction-private-runtime-route",
        id: WEBGPU_PRIVATE_TARGET_ID,
      },
      supportDisposition: "supported-construction-private-only",
      capsecDisposition: semantics.privateCellDisposition,
      implementationBranchIds: branches,
      providerBridgeEdgeId:
        semantics.providerBridge === null
          ? null
          : bridgeEdges[semantics.providerBridge],
      positiveAuthority: semantics.positiveAuthority,
      authoritySession: semantics.authoritySession,
      publicInstallDisposition: "absent",
      platformSupportClaim: "none",
    });
  }
  const presentationBranches = [];
  for (const branch of WEBGPU_PRESENTATION_AUTHORITY_BRANCHES) {
    const semantics = webGpuPresentationAuthoritySemantics(
      branch.operationId,
    );
    const surfaceName =
      `construction-private:webgpu-presentation:${branch.operationId}`;
    const edge = edgeBySurfaceName(coverage, surfaceName);
    if (edge.classification !== semantics.classification) {
      throw new Error(
        `${branch.operationId}: generated presentation-authority edge classification drifted`,
      );
    }
    const expectedImplementation = expectedPresentationImplementationRow(
      branch,
      edge,
    );
    const implementationMatches = implementationRows.filter(
      (row) => row.edgeId === edge.id,
    );
    if (
      implementationMatches.length !== 1 ||
      canonical(implementationMatches[0]) !==
        canonical(expectedImplementation)
    ) {
      throw new Error(
        `${branch.operationId}: full CapSec presentation-authority projections are stale; run bun run generate:capsec-registry`,
      );
    }
    const implementationBranches = [expectedImplementation.branchId];
    const wp1Cells = targetCells.cells.filter((cell) => cell.edgeId === edge.id);
    if (
      wp1Cells.length === 0 ||
      wp1Cells.some(
        (cell) =>
          cell.disposition !== "unsupported" ||
          cell.fixtures.length !== 0 ||
          canonical(cell.implementationBranchIds) !==
            canonical(implementationBranches),
      )
    ) {
      throw new Error(
        `${branch.operationId}: presentation authority promoted a WP1 target cell or has stale projections`,
      );
    }
    const privateTargetCellId =
      `${edge.id}.${WEBGPU_PRIVATE_TARGET_ID}`;
    presentationBranches.push({
      id: branch.id,
      operationId: branch.operationId,
      edgeId: edge.id,
      privateTargetCellId,
      action: semantics.authoritySession.action,
      stages: semantics.authoritySession.stages,
      targetCellDisposition:
        semantics.authoritySession.targetCellDisposition,
    });
    privateTargetCells.push({
      id: privateTargetCellId,
      edgeId: edge.id,
      target: {
        kind: "construction-private-runtime-route",
        id: WEBGPU_PRIVATE_TARGET_ID,
      },
      supportDisposition: "supported-construction-private-only",
      capsecDisposition: semantics.privateCellDisposition,
      implementationBranchIds: implementationBranches,
      providerBridgeEdgeId: bridgeEdges[semantics.providerBridge],
      positiveAuthority: semantics.positiveAuthority,
      authoritySession: semantics.authoritySession,
      publicInstallDisposition: "absent",
      platformSupportClaim: "none",
    });
  }
  operations.sort((left, right) => compareText(left.operationId, right.operationId));
  presentationBranches.sort((left, right) => compareText(left.id, right.id));
  privateTargetCells.sort((left, right) => compareText(left.edgeId, right.edgeId));
  return {
    webgpuOperationRegistrySchema: "ibex/webgpu-private-capsec-operations/2",
    profile: "ibex/capsec/1",
    webgpuProfileId: authenticated.plan.profileId,
    webgpuScopeId: authenticated.plan.scopeId,
    status: "construction-private-source-derived-no-public-install",
    source: {
      productionPlanPath: WEBGPU_PRODUCTION_PLAN_PATH,
      productionPlanRawContentSha256: authenticated.planRawContentSha256,
      wrapperAuthorityPath: WEBGPU_WRAPPER_AUTHORITY_PATH,
      wrapperAuthorityRawContentSha256: authenticated.authorityRawContentSha256,
      authenticatedDigests: authenticated.authenticatedDigests,
    },
    providerIdentity: authenticated.providerIdentity,
    publicBoundary: {
      navigatorGpu: "absent",
      embeddedExecutableWebGpuCodecs: "absent",
      nativeFactory: "unsupported-null",
      wp1TargetAdvertisements: "empty",
      platformSupportClaim: "none",
      positiveGrantIssuer: "absent",
    },
    bridgeEdges,
    operationCount: operations.length,
    operations,
    presentationAuthority: {
      schema: WEBGPU_PRESENTATION_AUTHORITY_SCHEMA,
      captureOperationId: "GPUCanvasContext.getCurrentTexture",
      branches: presentationBranches,
      phasePrograms: WEBGPU_PRESENTATION_AUTHORITY_PHASE_PROGRAMS,
    },
    privateTargetCellCount: privateTargetCells.length,
    privateTargetCells,
  };
}

export function assertExactWebGpuPrivateOperationRegistry(actual, expected) {
  if (canonical(actual) !== canonical(expected)) {
    throw new Error(
      "WebGPU private CapSec registry differs from its authenticated source derivation",
    );
  }
}
