extern "C" ExactHermesRuntime* ex_hermes_create() {
  TRACE_START(total);
  TRACE_START(hermes_config);
  auto gcConfig = ::hermes::vm::GCConfig::Builder()
                      .withShouldRecordStats(true)
                      .withName("ibex-runtime")
                      .build();
  auto configBuilder = ::hermes::vm::RuntimeConfig::Builder().withGCConfig(gcConfig);
#if defined(EXACT_HAVE_HERMES_MICROTASK_CONFIG)
  configBuilder.withMicrotaskQueue(true);
#endif
  auto config = configBuilder.withEnableEval(true).build();
  TRACE_END(hermes_config);

  TRACE_START(hermes_init);
  auto runtime = facebook::hermes::makeHermesRuntime(config);
  TRACE_END(hermes_init);
  if (!runtime) {
    return nullptr;
  }
  TRACE_START(handle_alloc);
  auto handle = new ExactHermesRuntime();
  handle->runtime = std::move(runtime);
  handle->runtime_thread = std::this_thread::get_id();
#ifdef EXACT_HAVE_FRAME_ATTRIBUTION
  // @ref LLP 0013#mechanism-3 — cache the vm::Runtime so host-boundary checks can
  // resolve the executing frame's package principal. getVMRuntimeUnsafe() is the
  // documented (unstable) accessor on IHermes, which HermesRuntime implements.
  g_vm_runtime = handle->runtime->getVMRuntimeUnsafe();
  // Mark everything compiled during bootstrap (the module loader, the shared
  // runtime bundle, the lockdown/compartment installers, and all the trusted
  // deputy wrappers they install) with the runtime principal, so frame
  // attribution sees through those deputies to the real caller. Reset to the
  // root principal after installGlobals so eval/Function-minted Domains and user
  // code are attributed to root, not the runtime. @ref LLP 0013 Open-Q3
  if (g_vm_runtime != nullptr) {
    ex_hermes_vm_set_default_package_id(g_vm_runtime, kRuntimePrincipalId);
  }
#endif
  TRACE_END(handle_alloc);

  TRACE_START(debugger_init);
#if defined(HERMES_ENABLE_DEBUGGER) && EXACT_HAS_HERMES_ASYNC_DEBUGGER
  try {
    handle->debugger =
        std::make_shared<facebook::hermes::debugger::AsyncDebuggerAPI>(*handle->runtime);
    handle->debugger_available.store(true);
  } catch (const facebook::jsi::JSError& err) {
    ex_host_console_log(1, err.getMessage().c_str());
    disableDebugger(handle);
  } catch (const std::exception& err) {
    ex_host_console_log(1, err.what());
    disableDebugger(handle);
  } catch (...) {
    ex_host_console_log(1, "Debugger not available in this Hermes build.");
    disableDebugger(handle);
  }
#else
  disableDebugger(handle);
#endif
  TRACE_END(debugger_init);

  TRACE_START(install_globals);
  installGlobals(handle);
  TRACE_END(install_globals);

  // Web Streams API polyfill (ReadableStream, WritableStream, TransformStream).
  // Run after all global bootstrap scripts so ReadableStream can be wrapped
  // on the final runtime surface that user code observes.
  if (env_flag_enabled("EX_WEB_STREAMS_POLYFILL")) {
    TRACE_START(web_streams_polyfill);
    installWebStreamsPolyfill(handle);
    TRACE_END(web_streams_polyfill);
  } else if (startup_trace_enabled()) {
    fprintf(stderr, "[startup]   web_streams_polyfill skipped (set EX_WEB_STREAMS_POLYFILL=1 to enable)\n");
  }
  registerRuntime(handle);

#ifdef EXACT_HAVE_FRAME_ATTRIBUTION
  // Bootstrap and all built-in polyfills are installed; from here on, code
  // compiled with no explicit principal (eval/Function, or any stray script the
  // embedder evaluates) is attributed to the root principal rather than the
  // runtime. Package code is stamped explicitly by the loader. @ref LLP 0013 Open-Q3
  if (g_vm_runtime != nullptr) {
    ex_hermes_vm_set_default_package_id(g_vm_runtime, 0);
    // @ref LLP 0013#phase-5 (Open-Q3) — arm schedule-time principal capture only
    // when deputy-class hardening is configured (policy `deputyClasses`), so
    // enqueueJob pays the stack walk only when the captured scheduler can be
    // consumed by the deputy-class stack AND. The policy is applied to the host
    // before the runtime is created (Host::new → install_host precede
    // create_engine), so ex_host_has_deputy_classes() is authoritative here. This
    // is the sole record of who scheduled a job once it drains detached, closing
    // the async deputy-laundering hole (`Promise.resolve(x).then(deputy.method)`).
    ex_hermes_vm_set_job_scheduler_capture(
        g_vm_runtime, ex_host_has_deputy_classes());
  }
#endif

  TRACE_END(total);
  return handle;
}

extern "C" void ex_hermes_destroy(ExactHermesRuntime* runtime) {
  if (runtime == nullptr) {
    return;
  }
  disableDebugger(runtime);
  unregisterAndroidHostFunctions(runtime);
  unregisterRuntime(runtime);
  delete runtime;
}

extern "C" int ex_hermes_eval(
    ExactHermesRuntime* runtime,
    const uint8_t* data,
    size_t len,
    const char* source_url,
    int is_bytecode,
    char** out_value) {
  auto writeOutError = [&](const std::string& text) -> bool {
    if (!out_value) {
      return true;
    }

    char* heap = static_cast<char*>(malloc(text.size() + 1));
    if (!heap) {
      return false;
    }
    memcpy(heap, text.data(), text.size());
    heap[text.size()] = '\0';
    *out_value = heap;
    return true;
  };

  if (out_value) {
    *out_value = nullptr;
  }

  if (!runtime || !data || len == 0) {
    writeOutError("Hermes eval received invalid input");
    return 1;
  }

  std::string source = source_url ? source_url : (is_bytecode ? "<bytecode>" : "<eval>");
  bool traceEval = startup_trace_enabled();
  if (!is_bytecode) {
    runtime->sources_by_name[source] = std::string(reinterpret_cast<const char*>(data), len);
  }

  try {
    auto writeOutString = [&](const std::string& text) -> bool {
      if (!out_value) {
        return true;
      }

      char* heap = static_cast<char*>(malloc(text.size() + 1));
      if (!heap) {
        return false;
      }
      memcpy(heap, text.data(), text.size());
      heap[text.size()] = '\0';
      *out_value = heap;
      return true;
    };

    facebook::jsi::Value result;
    std::shared_ptr<facebook::jsi::Buffer> source_buffer;
    if (is_bytecode) {
      source_buffer = std::make_shared<AlignedBytecodeBuffer>(data, len);
      auto aligned_data = source_buffer->data();
#if defined(EXACT_HAVE_HERMES_RUNTIME_BYTECODE_SANITY_CHECK)
      const auto* disable_check = std::getenv("EX_DISABLE_BYTECODE_SANITY_CHECK");
      if (!disable_check) {
        std::string reason;
        if (!facebook::hermes::HermesRuntime::hermesBytecodeSanityCheck(
                aligned_data, len, &reason)) {
          if (out_value) {
            char* heap = static_cast<char*>(malloc(reason.size() + 1));
            if (heap) {
              memcpy(heap, reason.data(), reason.size());
              heap[reason.size()] = '\0';
              *out_value = heap;
            }
          }
          return 1;
        }
      }
#else
      (void)aligned_data;
#endif
      result = runtime->runtime->evaluateJavaScript(source_buffer, source);
    } else {
      source_buffer = std::make_shared<MemoryBuffer>(data, len);
      if (traceEval) {
        fprintf(stderr, "[eval] evaluate_start %s len=%zu\n", source.c_str(), len);
      }
      result = runtime->runtime->evaluateJavaScript(source_buffer, source);
    }
    if (traceEval) {
      fprintf(stderr, "[eval] evaluate_end %s\n", source.c_str());
    }
    if (traceEval) {
      fprintf(stderr, "[eval] next_tick_start %s\n", source.c_str());
    }
    runNextTickQueue(runtime);
    if (traceEval) {
      fprintf(stderr, "[eval] next_tick_end %s\n", source.c_str());
      fprintf(stderr, "[eval] microtasks_start %s\n", source.c_str());
    }
    drainMicrotasks(*runtime->runtime);
    if (traceEval) {
      fprintf(stderr, "[eval] microtasks_end %s\n", source.c_str());
    }
#if EXACT_HAS_HERMES_ASYNC_DEBUGGER
    if (runtime->debugger_attached.load()) {
      emitNewScripts(runtime, runtime->runtime->getDebugger());
    }
#endif

    // If the result is a thenable/Promise, resolve it before returning.
    // This makes top-level await work in the REPL and eval contexts.
    // Windows Hermes currently does not support async function syntax in this
    // eval path, and the CLI already drives the event loop after file/eval
    // execution, so skip the JS unwrap shim there.
#if !defined(_WIN32)
    if (result.isObject()) {
      auto& rt = *runtime->runtime;
      // Stash the result as a temp global so JS can inspect it
      rt.global().setProperty(rt, "__ex_p",
          facebook::jsi::Value(rt, result));
      const char* unwrap_code =
          "(function(){"
          "var p=globalThis.__ex_p;"
          "delete globalThis.__ex_p;"
          "if(!p||typeof p.then!=='function')return null;"
          "var r={v:undefined,ok:true,done:false};"
          "p.then(function(v){r.v=v;r.done=true;},"
          "function(e){r.v=e;r.ok=false;r.done=true;});"
          "return r;"
          "})()";
      auto ubuf = std::make_shared<MemoryBuffer>(
          reinterpret_cast<const uint8_t*>(unwrap_code),
          strlen(unwrap_code));
      auto check = rt.evaluateJavaScript(ubuf, "<promise-unwrap>");
      drainMicrotasks(rt);

      if (!check.isNull() && check.isObject()) {
        auto promiseState = check.getObject(rt);
        auto resolvePromiseResult = [&]() -> std::optional<bool> {
          auto doneProp = promiseState.getProperty(rt, "done");
          if (!doneProp.isBool() || !doneProp.getBool()) {
            return std::nullopt;
          }

          auto ok = promiseState.getProperty(rt, "ok");
          if (ok.isBool() && ok.getBool()) {
            result = promiseState.getProperty(rt, "v");
            return true;
          }

          auto errVal = promiseState.getProperty(rt, "v");
          if (!writeOutString(valueToString(rt, errVal))) {
            return false;
          }
          return false;
        };

        while (true) {
          auto settled = resolvePromiseResult();
          if (settled.has_value()) {
            if (!settled.value()) {
              return 1;
            }
            break;
          }

          int executed = ex_hermes_poll(runtime, nowMs());
          if (executed < 0) {
            if (!writeOutString("Hermes task execution failed while awaiting Promise result")) {
              return 1;
            }
            return 1;
          }

          settled = resolvePromiseResult();
          if (settled.has_value()) {
            if (!settled.value()) {
              return 1;
            }
            break;
          }

          auto nextTimer = ex_hermes_next_timer(runtime);
          auto hasPendingWork = ex_hermes_has_pending_tasks(runtime) != 0;
          if (!hasPendingWork && nextTimer < 0) {
            // No timers or host work can advance the Promise any further.
            // Fall back to returning the raw Promise value rather than spin.
            break;
          }

          if (nextTimer >= 0) {
            auto now = nowMs();
            auto delay = nextTimer > static_cast<int64_t>(now)
                ? static_cast<uint64_t>(nextTimer) - now
                : 0;
            if (delay > 0) {
              std::this_thread::sleep_for(
                  std::chrono::milliseconds(std::min<uint64_t>(delay, 5)));
            }
          } else {
            std::this_thread::sleep_for(std::chrono::milliseconds(1));
          }
        }
      }
    }
#endif

    if (out_value) {
      if (result.isUndefined()) {
        *out_value = nullptr;
      } else {
        auto text = valueToString(*runtime->runtime, result);
        auto size = text.size();
        char* heap = static_cast<char*>(malloc(size + 1));
        if (!heap) {
          return 1;
        }
        memcpy(heap, text.data(), size);
        heap[size] = '\0';
        *out_value = heap;
      }
    }

    return 0;
  } catch (const facebook::jsi::JSError& err) {
    // Try to call process uncaughtException handler before reporting error
    auto& rt = *runtime->runtime;
    try {
      auto handler = rt.global().getProperty(rt, "__exactUncaughtExceptionHandler");
      if (handler.isObject() && handler.asObject(rt).isFunction(rt)) {
        // Create a new Error object from the message (can't copy jsi::Value)
        auto errObj = rt.global()
            .getPropertyAsFunction(rt, "Error")
            .callAsConstructor(rt, facebook::jsi::String::createFromUtf8(rt, err.getMessage()));
        auto result = handler.asObject(rt).asFunction(rt).call(rt, std::move(errObj));
        if (result.isBool() && result.getBool()) {
          // Handler returned true — exception was handled, don't crash
          if (out_value) *out_value = nullptr;
          return 0;
        }
      }
    } catch (...) {
      // If the handler itself throws, fall through to normal error reporting
    }

    if (out_value) {
      auto message = err.getMessage();
      auto stack = err.getStack();
      // Include stack trace if available
      std::string full;
      if (!stack.empty()) {
        full = message + "\n" + stack;
      } else {
        full = message;
      }
      auto size = full.size();
      char* heap = static_cast<char*>(malloc(size + 1));
      if (!heap) {
        return 1;
      }
      memcpy(heap, full.data(), size);
      heap[size] = '\0';
      *out_value = heap;
    }
    return 1;
  } catch (const std::exception& err) {
    if (out_value) {
      auto message = std::string(err.what());
      auto size = message.size();
      char* heap = static_cast<char*>(malloc(size + 1));
      if (!heap) {
        return 1;
      }
      memcpy(heap, message.data(), size);
      heap[size] = '\0';
      *out_value = heap;
    }
    return 1;
  } catch (...) {
    std::string source_label = source_url ? source_url : (is_bytecode ? "<bytecode>" : "<eval>");
    if (!writeOutError("Unknown non-std exception while evaluating " + source_label)) {
      return 1;
    }
    return 1;
  }
}

// --- Valet host-call bridge ---

extern "C" void ex_hermes_set_host_call(
    ExactHermesRuntime* runtime,
    char* (*callback)(const char* op, const char* args_json)) {
  if (!runtime) return;
  runtime->host_call_fn = callback;

  // Install (or reinstall) the __hostCall JS function
  auto& rt = *runtime->runtime;
  auto hostCallFn = facebook::jsi::Function::createFromHostFunction(
      rt,
      facebook::jsi::PropNameID::forAscii(rt, "__hostCall"),
      2,
      [runtime](facebook::jsi::Runtime& rt,
                const facebook::jsi::Value&,
                const facebook::jsi::Value* args,
                size_t count) -> facebook::jsi::Value {
        if (!runtime->host_call_fn || count < 2) {
          throw facebook::jsi::JSError(rt, "__hostCall: no callback registered or wrong arity");
        }
        auto op = args[0].asString(rt).utf8(rt);
        auto argsJson = args[1].asString(rt).utf8(rt);

        char* result = runtime->host_call_fn(op.c_str(), argsJson.c_str());
        if (!result) {
          return facebook::jsi::Value::null();
        }

        // Parse the result — first char indicates success/error:
        // '+' prefix = success, result JSON follows
        // '-' prefix = error, error message follows
        std::string resultStr(result);
        free(result);

        if (resultStr.empty()) {
          return facebook::jsi::Value::null();
        }

        if (resultStr[0] == '-') {
          throw facebook::jsi::JSError(rt, resultStr.substr(1));
        }

        // Parse the JSON result (skip '+' prefix)
        std::string json = (resultStr[0] == '+') ? resultStr.substr(1) : resultStr;
        if (json.empty() || json == "null" || json == "undefined") {
          return facebook::jsi::Value::null();
        }

        // Use JSON.parse to convert
        auto jsonGlobal = rt.global().getPropertyAsObject(rt, "JSON");
        auto parseFn = jsonGlobal.getPropertyAsFunction(rt, "parse");
        return parseFn.call(rt, facebook::jsi::String::createFromUtf8(rt, json));
      });
  rt.global().setProperty(rt, "__hostCall", std::move(hostCallFn));
}

extern "C" void ex_hermes_free_string(char* value) {
  if (value) {
    free(value);
  }
}

extern "C" int ex_hermes_poll(ExactHermesRuntime* runtime, uint64_t now_ms) {
  if (!runtime) {
    return 0;
  }

  int executed = 0;
  cleanupFetchCallbacks(runtime);

  // Drain cross-thread callback queue (HTTP server responses, etc.)
  executed += drainCallbackQueue(runtime);

  // Drain pending cross-thread tasks
  {
    std::vector<std::function<void(facebook::jsi::Runtime&)>> tasks;
    {
      std::lock_guard<std::mutex> lock(runtime->task_mutex);
      tasks.swap(runtime->pending_tasks);
    }
    if (!tasks.empty()) {
      auto& rt = *runtime->runtime;
      for (auto& task : tasks) {
        try {
          task(rt);
          executed++;
        } catch (const facebook::jsi::JSError& err) {
          ex_host_console_log(1, err.getMessage().c_str());
        } catch (const std::exception& err) {
          ex_host_console_log(1, err.what());
        }
      }
    }
  }

  runNextTickQueue(runtime);
  drainMicrotasks(*runtime->runtime);

  // Check if there are any referenced tasks keeping the loop alive
  // (excluding unref'd timers). If not, skip unref'd due timers.
  bool has_referenced_work = false;
  if (ex_host_http_has_referenced() || ex_host_http_has_pending_requests()
      || native_ws_has_active() || hasPendingFetchCallbacks(runtime)) {
    has_referenced_work = true;
  } else if (!runtime->next_tick.empty()) {
    has_referenced_work = true;
  } else if (runtime->active_spawn_processes.load(std::memory_order_relaxed) > 0) {
    has_referenced_work = true;
  } else {
    std::lock_guard<std::mutex> lock(runtime->callbackMutex);
    if (!runtime->callbackQueue.empty()) has_referenced_work = true;
  }
  if (!has_referenced_work) {
    // Check if any referenced timer exists
    for (const auto& kv : runtime->timers) {
      if (kv.second.referenced) {
        has_referenced_work = true;
        break;
      }
    }
  }

  std::vector<uint64_t> due;
  for (const auto& kv : runtime->timers) {
    if (kv.second.due_ms <= now_ms) {
      // Skip unref'd timers if nothing else is keeping the loop alive
      if (!kv.second.referenced && !has_referenced_work) {
        continue;
      }
      due.push_back(kv.first);
    }
  }
  // Sort by timer ID to maintain insertion order (IDs are monotonically increasing)
  std::sort(due.begin(), due.end());

  for (auto id : due) {
    auto it = runtime->timers.find(id);
    if (it == runtime->timers.end()) {
      continue;
    }
    // Retire or reschedule the fired timer. Must run before any error return
    // below: otherwise a throwing one-shot timer stays due and refires on
    // every subsequent poll. @ref LLP 0006#degrade-diagnostics-never-the-caller
    auto retireTimer = [runtime, now_ms, id]() {
      auto after = runtime->timers.find(id);
      if (after != runtime->timers.end()) {
        if (after->second.repeat) {
          after->second.due_ms = now_ms + after->second.interval_ms;
        } else {
          runtime->timers.erase(after);
        }
      }
    };
    try {
      if (it->second.args.empty()) {
        it->second.callback.call(*runtime->runtime);
      } else {
        it->second.callback.call(
            *runtime->runtime,
            static_cast<const facebook::jsi::Value*>(it->second.args.data()),
            it->second.args.size());
      }
      executed += 1;
      runNextTickQueue(runtime);
      drainMicrotasks(*runtime->runtime);
    } catch (const facebook::jsi::JSError& err) {
      executed += 1;
      // Try uncaughtException handler before terminating
      bool handled = false;
      try {
        auto& rt = *runtime->runtime;
        auto handler = rt.global().getProperty(rt, "__exactUncaughtExceptionHandler");
        if (handler.isObject() && handler.asObject(rt).isFunction(rt)) {
          auto errVal = facebook::jsi::Value(rt, err.value());
          auto result = handler.asObject(rt).asFunction(rt).call(rt, std::move(errVal));
          if (result.isBool() && result.getBool()) handled = true;
        }
      } catch (...) {}
      if (!handled) {
        retireTimer();
        ex_host_console_log(1, err.getMessage().c_str());
        return -1;
      }
      // Continue processing remaining timers after handled exception
      runNextTickQueue(runtime);
      drainMicrotasks(*runtime->runtime);
    } catch (const std::exception& err) {
      retireTimer();
      ex_host_console_log(1, err.what());
      return -1;
    }

    retireTimer();
  }

  return executed;
}

extern "C" int64_t ex_hermes_next_timer(ExactHermesRuntime* runtime) {
  if (!runtime || runtime->timers.empty()) {
    return -1;
  }
  uint64_t next_due = UINT64_MAX;
  for (const auto& kv : runtime->timers) {
    if (kv.second.due_ms < next_due) {
      next_due = kv.second.due_ms;
    }
  }
  if (next_due == UINT64_MAX) {
    return -1;
  }
  return static_cast<int64_t>(next_due);
}

extern "C" int ex_hermes_has_pending_tasks(ExactHermesRuntime* runtime) {
  if (!runtime) {
    return 0;
  }
  if (ex_host_http_has_referenced() || ex_host_http_has_pending_requests()
      || native_ws_has_active() || hasPendingFetchCallbacks(runtime)) {
    return 1;
  }
  if (!runtime->next_tick.empty()) {
    return 1;
  }
  if (runtime->active_spawn_processes.load(std::memory_order_relaxed) > 0) {
    return 1;
  }
  {
    std::lock_guard<std::mutex> lock(runtime->callbackMutex);
    if (!runtime->callbackQueue.empty()) return 1;
  }
  // Only count referenced timers as keeping the loop alive
  for (const auto& kv : runtime->timers) {
    if (kv.second.referenced) {
      return 1;
    }
  }
  return 0;
}

extern "C" uint32_t ex_hermes_callback_backlog(ExactHermesRuntime* runtime) {
  if (!runtime) {
    return 0;
  }

  std::lock_guard<std::mutex> lock(runtime->callbackMutex);
  return static_cast<uint32_t>(runtime->callbackQueue.size());
}

extern "C" void ex_hermes_schedule_watchdog_heartbeat(
    ExactHermesRuntime* runtime,
    void (*callback)(void* context),
    void* context) {
  if (!runtime || !callback) {
    return;
  }

  pushRuntimeCallback(runtime, [callback, context](facebook::jsi::Runtime&) {
    callback(context);
  });
}

