bool startup_trace_enabled() {
  static int cached = -1;
  if (cached < 0) {
    const char* val = std::getenv("EX_STARTUP_TRACE");
    cached = (val && (val[0] == '1' || val[0] == 'y' || val[0] == 'Y')) ? 1 : 0;
  }
  return cached == 1;
}

bool env_flag_enabled(const char* env_name) {
  // Shared truthiness parse: a leading 1/y/Y/t/T enables (so `1`, `yes`, `true`
  // all work), everything else (0/false/no/off/empty/unset) disables. The Rust
  // `env_flag_enabled` (src/bin/ibex/main.rs) mirrors this so the bundler driver
  // and the engine never disagree about whether compartments are on. (ENG-22634)
#if defined(_WIN32)
  // @ref LLP 0021#wp9--make-complete-enforcement-the-default-and-remove-weakening-paths —
  // Rust enables the production isolation flags before allocating Hermes. The Rust
  // standard library updates the Win32 process environment, while MSVC's CRT
  // can retain a separate getenv snapshot, so query the process environment
  // directly and observe the same value the Rust caller just installed.
  const DWORD required = GetEnvironmentVariableA(env_name, nullptr, 0);
  if (required == 0) {
    return false;
  }
  std::string value(required, '\0');
  const DWORD length =
      GetEnvironmentVariableA(env_name, value.data(), required);
  if (length == 0 || length >= required) {
    return false;
  }
  const char first = value.front();
#else
  const char* value = std::getenv(env_name);
  if (!value) {
    return false;
  }
  const char first = value[0];
#endif
  return first == '1' || first == 'y' || first == 'Y' ||
      first == 't' || first == 'T';
}

extern "C" void ex_host_console_log(int32_t level, const char* message);

#ifdef IBEX_CAPSEC_CONFORMANCE_OBSERVER
thread_local std::string g_injected_armed_startup_failure_stage;
// Test-only proof that one Exact completion capability traversed the resolver,
// callback queue, and runtime delivery exactly once. Ordinary artifacts do not
// compile this observer, and it cannot authorize or complete an operation.
// @ref LLP 0021#wp10--prove-targets-and-publish-the-conformance-report
std::atomic<uint64_t> g_exact_host_completion_targets_consumed{0};
std::atomic<uint64_t> g_exact_host_completion_callbacks_queued{0};
std::atomic<uint64_t> g_exact_host_completion_callbacks_delivered{0};

extern "C" void ibex_test_set_armed_startup_failure_stage(const char* stage) {
  g_injected_armed_startup_failure_stage = stage ? stage : "";
}

extern "C" void ibex_test_reset_exact_host_completion_observer() {
  g_exact_host_completion_targets_consumed.store(0, std::memory_order_seq_cst);
  g_exact_host_completion_callbacks_queued.store(0, std::memory_order_seq_cst);
  g_exact_host_completion_callbacks_delivered.store(0, std::memory_order_seq_cst);
}

extern "C" int ibex_test_exact_host_completion_observation(
    uint64_t* targets_consumed,
    uint64_t* callbacks_queued,
    uint64_t* callbacks_delivered) {
  if (targets_consumed == nullptr || callbacks_queued == nullptr ||
      callbacks_delivered == nullptr) {
    return 0;
  }
  *targets_consumed =
      g_exact_host_completion_targets_consumed.load(std::memory_order_seq_cst);
  *callbacks_queued =
      g_exact_host_completion_callbacks_queued.load(std::memory_order_seq_cst);
  *callbacks_delivered =
      g_exact_host_completion_callbacks_delivered.load(std::memory_order_seq_cst);
  return 1;
}
#endif

void requireArmedStartupStage(ExactHermesRuntime* handle, const char* stage) {
#ifdef IBEX_CAPSEC_CONFORMANCE_OBSERVER
  if (handle != nullptr && handle->armed && stage != nullptr &&
      g_injected_armed_startup_failure_stage == stage) {
    throw std::runtime_error(
        std::string("injected armed startup failure at ") + stage);
  }
#else
  (void)handle;
  (void)stage;
#endif
}

void reportStartupFailure(ExactHermesRuntime* handle,
                          const char* stage,
                          const std::string& detail) {
  std::string message = std::string(stage ? stage : "startup") +
      " failed" + (detail.empty() ? std::string() : ": " + detail);
  ex_host_console_log(1, message.c_str());
  if (handle != nullptr && handle->armed) {
    // Armed construction is transactional. A failed bootstrap/install stage
    // may not degrade into a partially hardened runtime that later happens to
    // satisfy a few marker checks.
    // @ref LLP 0021#wp4--arm-immutable-snapshots-through-the-cli-host-and-engine
    throw std::runtime_error(message);
  }
}

