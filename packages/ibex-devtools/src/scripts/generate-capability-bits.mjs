import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..', '..', '..', '..');
const SCRIPT_PATH = 'packages/ibex-devtools/src/scripts/generate-capability-bits.mjs';

export const capabilityBitSourcePath = path.join(
  repoRoot,
  'src',
  'host',
  'capability_bits.rs',
);

export const tsCapabilityBitOutputPath = path.join(
  repoRoot,
  'packages',
  'ibex-runtime-js',
  'src',
  'security',
  'capability-bits.generated.ts',
);

const ENTRY_RE =
  /CapabilityBitDefinition\s*\{\s*capability:\s*"([^"]+)",\s*bit:\s*(\d+)\s*\}/g;

function indexOfOutsideStrings(source, needle, start = 0) {
  let inString = false;
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
    } else if (character === '"') {
      inString = true;
    } else if (source.startsWith(needle, index)) {
      return index;
    }
  }
  return -1;
}

function capabilityTableBody(source) {
  const declaration = 'pub const CAPABILITY_BIT_DEFINITIONS:';
  const declarationStart = indexOfOutsideStrings(source, declaration);
  const equals = indexOfOutsideStrings(source, '=', declarationStart + declaration.length);
  const arrayStart = indexOfOutsideStrings(source, '&[', equals + 1);
  if (declarationStart < 0 || equals < 0 || arrayStart < 0) {
    throw new Error('CAPABILITY_BIT_DEFINITIONS table was not found');
  }
  let depth = 1;
  let inString = false;
  let escaped = false;
  for (let index = arrayStart + 2; index < source.length; index += 1) {
    const character = source[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
    } else if (character === '"') {
      inString = true;
    } else if (character === '[') {
      depth += 1;
    } else if (character === ']') {
      depth -= 1;
      if (depth === 0) return source.slice(arrayStart + 2, index);
    }
  }
  throw new Error('CAPABILITY_BIT_DEFINITIONS table is unterminated');
}

function stripRustComments(source) {
  let output = '';
  let inString = false;
  let escaped = false;
  let lineComment = false;
  let blockDepth = 0;

  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];
    const next = source[index + 1];
    if (lineComment) {
      if (character === '\n') {
        lineComment = false;
        output += character;
      } else {
        output += ' ';
      }
      continue;
    }
    if (blockDepth > 0) {
      if (character === '/' && next === '*') {
        blockDepth += 1;
        output += '  ';
        index += 1;
      } else if (character === '*' && next === '/') {
        blockDepth -= 1;
        output += '  ';
        index += 1;
      } else {
        output += character === '\n' ? '\n' : ' ';
      }
      continue;
    }
    if (inString) {
      output += character;
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') {
      inString = true;
      output += character;
    } else if (character === '/' && next === '/') {
      lineComment = true;
      output += '  ';
      index += 1;
    } else if (character === '/' && next === '*') {
      blockDepth = 1;
      output += '  ';
      index += 1;
    } else {
      output += character;
    }
  }
  if (inString || blockDepth > 0) {
    throw new Error('unterminated string or block comment in CAPABILITY_BIT_DEFINITIONS');
  }
  return output;
}

export function parseCapabilityBitDefinitions(
  source = fs.readFileSync(capabilityBitSourcePath, 'utf8'),
) {
  const tableBody = capabilityTableBody(stripRustComments(source));
  const entries = [];
  for (const match of tableBody.matchAll(ENTRY_RE)) {
    entries.push({
      capability: match[1],
      bit: Number(match[2]),
    });
  }
  const rowCount = [...tableBody.matchAll(/CapabilityBitDefinition\s*\{/g)].length;
  if (entries.length === 0 || entries.length !== rowCount) {
    throw new Error('CAPABILITY_BIT_DEFINITIONS contains an unparseable row');
  }
  return entries;
}

export function renderTsCapabilityBits(entries = parseCapabilityBitDefinitions()) {
  const lines = entries.map(
    ({ capability, bit }) => `  ${JSON.stringify(capability)}: ${bit},`,
  );

  return `// @generated by ${SCRIPT_PATH}\n// Do not edit by hand.\n\nexport const CapabilityBit = {\n${lines.join('\n')}\n} as const satisfies Record<string, number>;\n\nexport type CapabilityBitName = keyof typeof CapabilityBit;\n`;
}

function checkGeneratedFile(outputPath, rendered) {
  return fs.existsSync(outputPath) && fs.readFileSync(outputPath, 'utf8') === rendered;
}

if (process.argv[1] === __filename) {
  const checkMode = process.argv.includes('--check');
  const tsOutput = renderTsCapabilityBits();

  if (checkMode) {
    const tsOk = checkGeneratedFile(tsCapabilityBitOutputPath, tsOutput);
    if (!tsOk) {
      console.error('Capability bit generated files are out of date.');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(tsCapabilityBitOutputPath, tsOutput, 'utf8');
    console.log(`Wrote ${path.relative(repoRoot, tsCapabilityBitOutputPath)}`);
  }
}
