// Shared args coercion for the sync and async host-call bridges
// (ENG-22885). Callers are supposed to pass a JSON *string* as the second
// argument, but raw-global callers (agents via run-js, exploratory code)
// routinely pass an object; `asString` on an object throws synchronously
// BEFORE the async bridge has created its promise, which kick-then-poll
// callers experience as "the promise never settles". Coerce instead:
// missing/undefined/null -> "{}", strings pass through, everything else is
// JSON.stringify'd.
std::string hostCallArgsToJson(facebook::jsi::Runtime& rt,
                               const facebook::jsi::Value* args,
                               size_t count) {
  if (count < 2 || args[1].isUndefined() || args[1].isNull()) {
    return "{}";
  }
  if (args[1].isString()) {
    return args[1].asString(rt).utf8(rt);
  }
  auto jsonGlobal = rt.global().getPropertyAsObject(rt, "JSON");
  auto stringifyFn = jsonGlobal.getPropertyAsFunction(rt, "stringify");
  auto serialized = stringifyFn.call(rt, args[1]);
  if (serialized.isString()) {
    return serialized.asString(rt).utf8(rt);
  }
  // JSON.stringify(function/symbol/undefined) returns undefined.
  return "{}";
}

// Coerce the host-call `op` (args[0]) to a std::string without a synchronous
// JSI throw (ENG-22982). The async bridge does not construct its Promise until
// AFTER this runs, so an `asString()` on a non-string op (number, object) threw
// before the promise existed — kick-then-poll callers saw a call that "never
// settles" instead of a rejected promise; the sync bridge had the same
// asymmetry (args were coerced but op was not). Mirror hostCallArgsToJson's
// coerce-don't-throw contract: strings pass through; anything else goes through
// the global String() (which, unlike ToString, tolerates symbols), and any
// residual throw (a pathological object toString) is swallowed to a sentinel so
// the caller reaches the host and gets a normal "Unknown host call" rejection
// rather than a synchronous throw.
std::string hostCallOpToString(facebook::jsi::Runtime& rt,
                               const facebook::jsi::Value* args,
                               size_t count) {
  if (count < 1) {
    return "";
  }
  if (args[0].isString()) {
    return args[0].asString(rt).utf8(rt);
  }
  try {
    auto stringCtor = rt.global().getPropertyAsFunction(rt, "String");
    auto coerced = stringCtor.call(rt, args[0]);
    if (coerced.isString()) {
      return coerced.asString(rt).utf8(rt);
    }
  } catch (const facebook::jsi::JSIException&) {
    // Fall through to the sentinel below.
  }
  return "";
}

// Shared '+json' / '-error' sigil decode for the sync and async host-call
// bridges. Returns true and writes `out` on success; returns false and
// writes `error_message` for a '-' payload. Empty / "null" / "undefined"
// payloads decode to JS null, matching the historical sync behavior.
bool decodeHostCallPayload(facebook::jsi::Runtime& rt,
                           const std::string& payload,
                           facebook::jsi::Value& out,
                           std::string& error_message) {
  if (payload.empty()) {
    out = facebook::jsi::Value::null();
    return true;
  }

  if (payload[0] == '-') {
    error_message = payload.substr(1);
    return false;
  }

  std::string json = (payload[0] == '+') ? payload.substr(1) : payload;
  if (json.empty() || json == "null" || json == "undefined") {
    out = facebook::jsi::Value::null();
    return true;
  }

  auto jsonGlobal = rt.global().getPropertyAsObject(rt, "JSON");
  auto parseFn = jsonGlobal.getPropertyAsFunction(rt, "parse");
  out = parseFn.call(rt, facebook::jsi::String::createFromUtf8(rt, json));
  return true;
}

