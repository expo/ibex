class AlignedBytecodeBuffer : public facebook::jsi::Buffer {
 public:
  AlignedBytecodeBuffer(const uint8_t* data, size_t len) : size_(len), data_(nullptr) {
    if (len == 0) {
      return;
    }
    const size_t alignment = alignof(std::max_align_t);
    size_t padded = (len + alignment - 1) & ~(alignment - 1);
#if defined(_WIN32)
    data_ = static_cast<uint8_t*>(_aligned_malloc(padded, alignment));
    if (!data_) {
      throw std::bad_alloc();
    }
#else
    if (posix_memalign(reinterpret_cast<void**>(&data_), alignment, padded) != 0) {
      data_ = nullptr;
      throw std::bad_alloc();
    }
#endif
    memcpy(data_, data, len);
  }

  ~AlignedBytecodeBuffer() {
    if (data_) {
#if defined(_WIN32)
      _aligned_free(data_);
#else
      free(data_);
#endif
    }
  }

  size_t size() const override { return size_; }
  const uint8_t* data() const override { return data_; }

 private:
  size_t size_{0};
  uint8_t* data_;
};

std::string valueToString(facebook::jsi::Runtime& rt, const facebook::jsi::Value& value) {
  if (value.isUndefined()) {
    return "undefined";
  }
  if (value.isNull()) {
    return "null";
  }
  if (value.isObject()) {
    // Check if this is an Error instance — Error properties are non-enumerable
    // so JSON.stringify returns "{}" which is useless.
    try {
      auto obj = value.getObject(rt);
      auto errorCtor = rt.global().getProperty(rt, "Error");
      if (errorCtor.isObject()) {
        auto isInstance = rt.global()
            .getPropertyAsObject(rt, "Object")
            .getPropertyAsFunction(rt, "getPrototypeOf");
        // Simple check: see if the object has a .message property (duck-type Error)
        auto msgProp = obj.getProperty(rt, "message");
        auto stackProp = obj.getProperty(rt, "stack");
        if (msgProp.isString()) {
          std::string result = msgProp.asString(rt).utf8(rt);
          if (stackProp.isString()) {
            auto stack = stackProp.asString(rt).utf8(rt);
            if (!stack.empty()) {
              result += "\n" + stack;
            }
          }
          return result;
        }
      }
    } catch (...) {
    }
    try {
      auto jsonObj = rt.global().getPropertyAsObject(rt, "JSON");
      auto stringify = jsonObj.getPropertyAsFunction(rt, "stringify");
      auto pretty = stringify.call(rt, value, facebook::jsi::Value::null(), facebook::jsi::Value(2.0));
      if (pretty.isString()) {
        return pretty.asString(rt).utf8(rt);
      }
    } catch (const facebook::jsi::JSError&) {
    } catch (...) {
    }
  }
  return value.toString(rt).utf8(rt);
}

facebook::jsi::Function makeLogFunction(facebook::jsi::Runtime& rt, int32_t level) {
  return facebook::jsi::Function::createFromHostFunction(
      rt,
      facebook::jsi::PropNameID::forAscii(rt, "log"),
      1,
      [level](facebook::jsi::Runtime& runtime,
              const facebook::jsi::Value&,
              const facebook::jsi::Value* args,
              size_t count) -> facebook::jsi::Value {
        std::string message;
        for (size_t i = 0; i < count; ++i) {
          if (i > 0) {
            message += " ";
          }
          message += valueToString(runtime, args[i]);
        }
        ex_host_console_log(level, message.c_str());
        return facebook::jsi::Value::undefined();
      });
}

uint64_t nowMs() {
  using namespace std::chrono;
  // Timer deadlines (setTimeout/setInterval store due_ms = nowMs() + delay) must
  // clock off a MONOTONIC source, like Node/libuv. system_clock is the wall
  // clock: a backward NTP/manual step postpones every pending timer by the step
  // size, and a forward step fires them all at once. steady_clock never jumps
  // backward and is unaffected by clock adjustments. The Rust event loop reads
  // this same source via ex_hermes_now_ms() for the `now` it feeds to
  // ex_hermes_poll, so both sides share one clock domain.
  return duration_cast<milliseconds>(steady_clock::now().time_since_epoch()).count();
}

// Expose the monotonic timer clock (nowMs) to the Rust event loop so the `now`
// it passes to ex_hermes_poll and the due_ms stored by setTimeout/setInterval
// are measured on the identical clock. Mixing a Rust std::time::Instant with the
// C++ steady_clock is not safe (their epochs are unspecified and may differ), so
// there is exactly one source of truth for timer time.
extern "C" uint64_t ex_hermes_now_ms() {
  return nowMs();
}

double processUptimeSeconds() {
  auto elapsed = std::chrono::duration<double>(std::chrono::steady_clock::now() -
                                               g_process_start_time);
  return elapsed.count();
}

[[noreturn]] void exactHostExit(int code) {
  // console.log lines travel through a bounded queue serviced by a writer
  // thread; terminating without draining it discards output enqueued in the
  // same tick (`console.log(...); process.exit(0)` printed nothing). Windows
  // lost the race deterministically — ExitProcess kills the writer thread and,
  // unlike std::exit, skips CRT stream flushing — but POSIX std::exit does not
  // wait for the writer thread either. Drain (bounded) on every platform, then
  // flush the C streams Windows would otherwise abandon. (ENG-23639)
  ex_host_console_flush(2000);
#if defined(_WIN32)
  std::fflush(stdout);
  std::fflush(stderr);
  ExitProcess(static_cast<UINT>(code));
#else
  std::exit(code);
#endif
}

facebook::jsi::Function makeHardExitFn(facebook::jsi::Runtime& rt) {
  auto fn = facebook::jsi::Function::createFromHostFunction(
      rt,
      facebook::jsi::PropNameID::forAscii(rt, "exit"),
      1,
      [](facebook::jsi::Runtime& runtime,
         const facebook::jsi::Value&,
         const facebook::jsi::Value* args,
         size_t count) -> facebook::jsi::Value {
        int code = 0;
        if (count > 0) {
          if (args[0].isNumber()) {
            code = static_cast<int>(args[0].asNumber());
          } else if (args[0].isString()) {
            try {
              code = std::stoi(args[0].getString(runtime).utf8(runtime));
            } catch (...) {
              code = 0;
            }
          }
        }
        try {
          auto processObj = runtime.global().getProperty(runtime, "process");
          if (!processObj.isObject()) {
            exactHostExit(code);
          }
          auto process = processObj.asObject(runtime);
          process.setProperty(runtime, "exitCode", facebook::jsi::Value(code));
        } catch (...) {
        }
        exactHostExit(code);
      });
  try {
    fn.setProperty(rt, "__exactHostExit", facebook::jsi::Value(true));
  } catch (...) {
  }
  return fn;
}

