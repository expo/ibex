/**
 * Source-derived CapSec inventory for Exact's construction-private WebGPU
 * wrapper plan.
 *
 * This registry deliberately does not participate in the executable WP1
 * target-advertisement plane. It records which authenticated private routes
 * have an operation edge and a construction-private target cell while every
 * provider-capable edge remains closed and every positive issuer remains
 * absent.
 *
 * @ref LLP 0002#the-optional-exact-gpu-service-registration-seam
 * @ref LLP 0021#generated-semantic-datasets
 */

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { validateWebGpuWrapperAuthority } from "./webgpu-test-wrapper-generator.mjs";

export const WEBGPU_PRODUCTION_PLAN_PATH =
  "packages/ibex-runtime-js/src/webgpu/production-plan.generated.ts";
export const WEBGPU_WRAPPER_AUTHORITY_PATH =
  "tests/fixtures/webgpu-test-wrapper-authority-v1.json";
export const WEBGPU_PRIVATE_TARGET_ID =
  "exact-construction-private-webgpu-v1";

const PLAN_PREFIX =
  "// Generated by generate-webgpu-production-plan.mjs; do not edit.\n" +
  "// The route table is production input, but navigator.gpu remains gated\n" +
  "// until a separately generated executable codec bundle validates it.\n" +
  "export const WEBGPU_PRODUCTION_PLAN = ";
const PLAN_SUFFIX = " as const;\n";

const ROUTE_KEYS = Object.freeze([
  "operationId",
  "wireId",
  "interfaceName",
  "memberName",
  "memberKind",
  "dispatchClass",
  "logicalExecutionKind",
  "resultTiming",
  "providerSubmission",
  "receiverHandleKind",
  "wrapperAllocatedTargetHandleKind",
  "resultHandleKind",
  "serviceReceiverProjection",
  "publicArgumentCodec",
  "serviceArgumentCodec",
  "serviceCompletionCodec",
  "publicResultCodec",
  "operationInstanceIdentity",
  "promiseIdentity",
]);

const BRIDGE_SURFACE_NAMES = Object.freeze({
  cancel: "construction-private:gpuNativeBridgeV2.cancel",
  createMappedRangeAlias:
    "construction-private:gpuNativeBridgeV2.createMappedRangeAlias",
  detachMappedRange:
    "construction-private:gpuNativeBridgeV2.detachMappedRange",
  retire: "construction-private:gpuNativeBridgeV2.retire",
  setEventSink: "construction-private:gpuNativeBridgeV2.setEventSink",
  submit: "construction-private:gpuNativeBridgeV2.submit",
});

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort(compareText)
      .map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function sha256Hex(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function fnv1a32(value) {
  let hash = 0x811c9dc5;
  for (const byte of new TextEncoder().encode(value)) {
    hash ^= byte;
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(36).padStart(7, "0");
}

function routeProjection(operation) {
  const operationId = operation.operationId;
  return {
    operationId,
    wireId: operation.wireId,
    interfaceName: operationId.slice(0, operationId.indexOf(".")),
    memberName: operationId.slice(operationId.indexOf(".") + 1),
    memberKind: operation.memberKind,
    dispatchClass: operation.dispatchClass,
    logicalExecutionKind: operation.logicalExecutionKind,
    resultTiming: operation.resultTiming,
    providerSubmission: operation.providerSubmission,
    receiverHandleKind: operation.receiverHandleKind,
    wrapperAllocatedTargetHandleKind:
      operation.wrapperAllocatedTargetHandleKind,
    resultHandleKind: operation.resultHandleKind,
    serviceReceiverProjection: operation.serviceReceiverProjection,
    publicArgumentCodec: operation.publicArgumentCodec,
    serviceArgumentCodec: operation.serviceArgumentCodec,
    serviceCompletionCodec: operation.serviceCompletionCodec,
    publicResultCodec: operation.publicResultCodec,
    operationInstanceIdentity: operation.operationInstanceIdentity,
    promiseIdentity: operation.promiseIdentity,
  };
}

export function parseWebGpuProductionPlanSource(
  source,
  label = WEBGPU_PRODUCTION_PLAN_PATH,
) {
  if (!source.startsWith(PLAN_PREFIX) || !source.endsWith(PLAN_SUFFIX)) {
    throw new Error(`${label}: generated production-plan envelope drifted`);
  }
  let plan;
  try {
    plan = JSON.parse(
      source.slice(PLAN_PREFIX.length, source.length - PLAN_SUFFIX.length),
    );
  } catch (error) {
    throw new Error(`${label}: invalid generated plan JSON: ${error.message}`);
  }
  if (
    plan?.schema !== "ibex/webgpu-production-wrapper-plan/1" ||
    !Array.isArray(plan.routes) ||
    plan.routes.length === 0
  ) {
    throw new Error(`${label}: invalid production-plan shape`);
  }
  return plan;
}

export function authenticateWebGpuProductionPlan({
  plan,
  authority,
  planRawContentSha256 = null,
  authorityRawContentSha256 = null,
}) {
  const authenticated = validateWebGpuWrapperAuthority(authority);
  const expectedRoutes = authenticated.payload.operations.map(routeProjection);
  if (canonical(plan.routes) !== canonical(expectedRoutes)) {
    throw new Error(
      "WebGPU production-plan routes differ from authenticated wrapper authority",
    );
  }
  if (
    plan.profileId !== authenticated.payload.profileId ||
    plan.scopeId !== authenticated.payload.scopeId ||
    canonical(plan.digests) !== canonical(authenticated.computed)
  ) {
    throw new Error(
      "WebGPU production-plan profile, scope, or digest identity is unauthenticated",
    );
  }
  const operationIds = expectedRoutes.map((route) => route.operationId);
  if (
    plan.activeRouteSubset?.scopeId !== plan.scopeId ||
    plan.activeRouteSubset?.operationCount !== expectedRoutes.length ||
    canonical(plan.activeRouteSubset?.operationIds) !== canonical(operationIds) ||
    plan.activeRouteSubset?.capsecDisposition !==
      "construction-private-source-derived-cells-public-closed"
  ) {
    throw new Error(
      "WebGPU production-plan active-route subset differs from authenticated routes",
    );
  }
  const stagedIds = new Set(
    (plan.stagedWorkloadClosure?.additionalOperations ?? []).map(
      (operation) => operation.operationId,
    ),
  );
  const stagedOverlap = operationIds.filter((operationId) =>
    stagedIds.has(operationId),
  );
  if (stagedOverlap.length > 0) {
    throw new Error(
      `WebGPU staged routes leaked into the active production plan: ${stagedOverlap.join(", ")}`,
    );
  }
  if (
    plan.productSemanticExtension?.publicInstallDisposition !== "absent" ||
    plan.productSemanticExtension?.embeddedCodecDisposition !== "absent" ||
    plan.productSemanticExtension?.supportClaim !== "none" ||
    plan.productSemanticExtension?.capsecDisposition !==
      "construction-private-source-derived-cells-public-closed"
  ) {
    throw new Error(
      "WebGPU production-plan product extension crossed the private support boundary",
    );
  }
  for (const [index, route] of expectedRoutes.entries()) {
    if (
      !Number.isInteger(route.wireId) ||
      route.wireId <= 0 ||
      Object.keys(route).some((key) => !ROUTE_KEYS.includes(key))
    ) {
      throw new Error(`WebGPU route ${index} has an invalid authenticated identity`);
    }
  }
  return {
    plan,
    routes: expectedRoutes,
    authenticatedDigests: authenticated.computed,
    planRawContentSha256,
    authorityRawContentSha256,
  };
}

export function loadAuthenticatedWebGpuProductionPlan(repoRoot) {
  const planPath = path.join(repoRoot, WEBGPU_PRODUCTION_PLAN_PATH);
  const authorityPath = path.join(repoRoot, WEBGPU_WRAPPER_AUTHORITY_PATH);
  const planBytes = fs.readFileSync(planPath);
  const authorityBytes = fs.readFileSync(authorityPath);
  const plan = parseWebGpuProductionPlanSource(
    new TextDecoder("utf-8", { fatal: true }).decode(planBytes),
  );
  let authority;
  try {
    authority = JSON.parse(
      new TextDecoder("utf-8", { fatal: true }).decode(authorityBytes),
    );
  } catch (error) {
    throw new Error(
      `${WEBGPU_WRAPPER_AUTHORITY_PATH}: invalid authority JSON: ${error.message}`,
    );
  }
  return authenticateWebGpuProductionPlan({
    plan,
    authority,
    planRawContentSha256: sha256Hex(planBytes),
    authorityRawContentSha256: sha256Hex(authorityBytes),
  });
}

export function webGpuOperationSemantics(route) {
  if (
    route.logicalExecutionKind === "cleanup-service" ||
    route.providerSubmission === "semantic-call-authority-reducing"
  ) {
    return {
      classification: "non-capability",
      rationaleId: "authority-release",
      privateCellDisposition: "non-capability",
      providerBridge: "submit",
      positiveAuthority: "not-applicable-authority-reducing",
    };
  }
  if (route.providerSubmission === "semantic-service-timeline") {
    return {
      classification: "non-capability",
      rationaleId: "authority-control-plane",
      privateCellDisposition: "non-capability",
      providerBridge: null,
      positiveAuthority: "not-applicable-control-plane",
    };
  }
  if (
    route.dispatchClass === "wrapper-local" ||
    route.dispatchClass === "wrapper-property-read"
  ) {
    return {
      classification: "non-capability",
      rationaleId:
        route.operationId === "GPU.getPreferredCanvasFormat"
          ? "pure-in-memory-compute"
          : "retained-object-wrapper",
      privateCellDisposition: "non-capability",
      providerBridge: null,
      positiveAuthority: "not-applicable-wrapper-local",
    };
  }
  if (route.dispatchClass === "wrapper-recording") {
    return {
      classification: "non-capability",
      rationaleId: "retained-object-wrapper",
      privateCellDisposition: "non-capability",
      providerBridge: null,
      positiveAuthority: "not-applicable-wrapper-recording",
    };
  }
  if (route.dispatchClass === "wrapper-local-deferred-service") {
    return {
      classification: "closed",
      cap: "ipc:channel",
      privateCellDisposition: "closed",
      providerBridge: null,
      positiveAuthority: "absent-closed-deferred-service-edge",
    };
  }
  if (
    route.providerSubmission === "semantic-call-promise-completion" ||
    route.providerSubmission === "semantic-call-device-timeline"
  ) {
    return {
      classification: "closed",
      cap: "ipc:channel",
      privateCellDisposition: "closed",
      providerBridge: "submit",
      positiveAuthority: "absent-closed-provider-edge",
    };
  }
  throw new Error(
    `${route.operationId}: unreviewed WebGPU CapSec route semantics ${route.dispatchClass}/${route.logicalExecutionKind}/${route.providerSubmission}`,
  );
}

export function buildWebGpuOperationSurfaces(authenticated) {
  return authenticated.routes.map((route) => {
    const semantics = webGpuOperationSemantics(route);
    const name = `construction-private:webgpu:${route.operationId}`;
    const sourceRefs = [
      `${WEBGPU_PRODUCTION_PLAN_PATH}#route:${route.operationId}:${route.wireId}`,
      `${WEBGPU_WRAPPER_AUTHORITY_PATH}#payload.operations:${route.operationId}:${route.wireId}`,
    ].sort(compareText);
    const branch = {
      branchKind: "single",
      id: `authenticated-production-route-${fnv1a32(`${route.operationId}\0${route.wireId}`)}`,
      kind: "single",
      route: "authenticated-webgpu-production-route",
      sourceRefs,
      targetVariant: "all",
    };
    return {
      kind: "native-op",
      name,
      observedKey: `native-op:${name}`,
      sourceRefs,
      metadata: {
        evidenceType: "authenticated-webgpu-production-route",
        surfaceType: "webgpu-production-operation",
        operationId: route.operationId,
        wireId: route.wireId,
        routeIdentity: route,
        authenticatedDigests: authenticated.authenticatedDigests,
        publicInstallDisposition: "absent",
        embeddedExecutableCodecDisposition: "absent",
        platformSupportClaim: "none",
        positiveAuthority: semantics.positiveAuthority,
        providerBridge: semantics.providerBridge,
        branches: [branch],
        installationBranches: [branch],
        semanticRoles: ["construction-private-webgpu-operation"],
      },
    };
  });
}

function edgeBySurfaceName(coverage, surfaceName) {
  const rows = coverage.edges.filter(
    (edge) =>
      edge.surface.kind === "native-op" && edge.surface.name === surfaceName,
  );
  if (rows.length !== 1) {
    throw new Error(
      `${surfaceName}: expected one generated CapSec edge, found ${rows.length}`,
    );
  }
  return rows[0];
}

export function buildWebGpuPrivateOperationRegistry({
  authenticated,
  coverage,
  implementationRows,
  targetCells,
  targetAdvertisements,
}) {
  if (targetAdvertisements.advertisements.length !== 0) {
    throw new Error(
      "construction-private WebGPU registry cannot promote a WP1 target advertisement",
    );
  }
  const bridgeEdges = Object.fromEntries(
    Object.entries(BRIDGE_SURFACE_NAMES).map(([name, surfaceName]) => [
      name,
      edgeBySurfaceName(coverage, surfaceName).id,
    ]),
  );
  const operations = [];
  const privateTargetCells = [];
  for (const route of authenticated.routes) {
    const semantics = webGpuOperationSemantics(route);
    const surfaceName = `construction-private:webgpu:${route.operationId}`;
    const edge = edgeBySurfaceName(coverage, surfaceName);
    if (edge.classification !== semantics.classification) {
      throw new Error(
        `${route.operationId}: generated edge classification drifted from route semantics`,
      );
    }
    const branches = implementationRows
      .filter((row) => row.edgeId === edge.id)
      .map((row) => row.branchId)
      .sort(compareText);
    if (branches.length !== 1) {
      throw new Error(
        `${route.operationId}: expected one source-derived implementation branch`,
      );
    }
    const wp1Cells = targetCells.cells.filter((cell) => cell.edgeId === edge.id);
    if (
      wp1Cells.length === 0 ||
      wp1Cells.some(
        (cell) => cell.disposition !== "unsupported" || cell.fixtures.length !== 0,
      )
    ) {
      throw new Error(
        `${route.operationId}: construction-private route promoted a WP1 target cell`,
      );
    }
    operations.push({
      operationId: route.operationId,
      wireId: route.wireId,
      edgeId: edge.id,
      edgeClassification: edge.classification,
      dispatchClass: route.dispatchClass,
      logicalExecutionKind: route.logicalExecutionKind,
      providerSubmission: route.providerSubmission,
      privateTargetCellId: `${edge.id}.${WEBGPU_PRIVATE_TARGET_ID}`,
    });
    privateTargetCells.push({
      id: `${edge.id}.${WEBGPU_PRIVATE_TARGET_ID}`,
      edgeId: edge.id,
      target: {
        kind: "construction-private-runtime-route",
        id: WEBGPU_PRIVATE_TARGET_ID,
      },
      supportDisposition: "supported-construction-private-only",
      capsecDisposition: semantics.privateCellDisposition,
      implementationBranchIds: branches,
      providerBridgeEdgeId:
        semantics.providerBridge === null
          ? null
          : bridgeEdges[semantics.providerBridge],
      positiveAuthority: semantics.positiveAuthority,
      publicInstallDisposition: "absent",
      platformSupportClaim: "none",
    });
  }
  operations.sort((left, right) => compareText(left.operationId, right.operationId));
  privateTargetCells.sort((left, right) => compareText(left.edgeId, right.edgeId));
  return {
    webgpuOperationRegistrySchema: "ibex/webgpu-private-capsec-operations/1",
    profile: "ibex/capsec/1",
    webgpuProfileId: authenticated.plan.profileId,
    webgpuScopeId: authenticated.plan.scopeId,
    status: "construction-private-source-derived-no-public-install",
    source: {
      productionPlanPath: WEBGPU_PRODUCTION_PLAN_PATH,
      productionPlanRawContentSha256: authenticated.planRawContentSha256,
      wrapperAuthorityPath: WEBGPU_WRAPPER_AUTHORITY_PATH,
      wrapperAuthorityRawContentSha256: authenticated.authorityRawContentSha256,
      authenticatedDigests: authenticated.authenticatedDigests,
    },
    publicBoundary: {
      navigatorGpu: "absent",
      embeddedExecutableWebGpuCodecs: "absent",
      nativeFactory: "unsupported-null",
      wp1TargetAdvertisements: "empty",
      platformSupportClaim: "none",
      positiveGrantIssuer: "absent",
    },
    bridgeEdges,
    operationCount: operations.length,
    operations,
    privateTargetCellCount: privateTargetCells.length,
    privateTargetCells,
  };
}

export function assertExactWebGpuPrivateOperationRegistry(actual, expected) {
  if (canonical(actual) !== canonical(expected)) {
    throw new Error(
      "WebGPU private CapSec registry differs from its authenticated source derivation",
    );
  }
}
